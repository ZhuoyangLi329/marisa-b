"""Post-reconstruction IR resummation for MARISA-B's finite-PNG halo tree.

This module extends :mod:`marisa_b.tree_png_ir_resummation` to the actual
post-reconstruction semantics implemented in ``marisa_b_native.cpp``.  It is
an auditable Python oracle, not a replacement for the native production path.

The implementation keeps only the tree-level finite-local-PNG model

    B_h(f) = G + f L + f**2 Q,

and the controlled leading-wiggle IR result.  It deliberately contains no
one-loop contribution and no tree/loop matching counterterm.

Two distinct effects are included:

1. **Source reconstruction.**  The native reconstructed kernels already
   modify the tree source.  We evaluate the fixed-``b_rec`` terms and, when
   requested, the native adaptive-denominator bases generated by

       b_rec(q; f_rec) = b_rec + f_rec bphi_rec / M(q),
       f_rec = eta * f.

2. **Displacement damping.**  The long reconstructed displacement is

       Psi_rec^L(q) = C(q; f) Psi^L(q),
       C(q; f) = 1 - W_rec(q)
                      [b1 + f bphi/M(q)]
                      / [b_rec + eta f bphi_rec/M(q)].

   Consequently the BAO displacement variance and the damping exponent have
   their own finite-PNG expansion.  Through O(f**2), this mixes the Gaussian
   one-wiggle source into L and Q and mixes the linear-PNG one-wiggle source
   into Q.  These terms are absent if one merely applies a fixed Gaussian
   damping factor to the post-reconstruction G/L/Q source components.

For a Cartesian CIC reconstruction window the displacement covariance is
orientation dependent.  The ``cartesian`` branch evaluates the angular
integral for each external leg before shell/orientation projection.  When CIC
is disabled, the faster isotropic formula is used and all three legs share a
single variance.

The strict one-wiggle result implemented here is

    G_IR = G_nw + sum_i D0_i Gwi,

    L_IR = L_nw + sum_i D0_i [Lwi + d1_i Gwi],

    Q_IR = Q_nw + sum_i D0_i [Qwi + d1_i Lwi + d2_i Gwi],

where

    D_i(f) = exp[-k_i**2 (S0_i + f S1_i + f**2 S2_i)]
           = D0_i [1 + f d1_i + f**2 d2_i] + O(f**3),

    d1_i = -k_i**2 S1_i,
    d2_i = 0.5 k_i**4 S1_i**2 - k_i**2 S2_i.

``S0/S1/S2`` are coefficients of the reconstructed BAO displacement
variance, not powers of one common number.  In the matched adaptive limit
``b_rec=b1``, ``bphi_rec=bphi`` and ``eta=1``, the ratio in ``C`` is exactly
one and all finite-PNG damping responses vanish.

Scope and caveats
-----------------
* Real space only, matching the current MARISA-B tree oracle.
* Strict leading-wiggle O(P_w) only.  The wiggle-wiggle ULPT closure is not
  silently added.
* The long displacement is Gaussian and linear.  Primordial higher
  displacement cumulants are not resummed; this is the same leading-IR
  counting used by the tree-level BAO prescription.
* A positive finite ``q_min`` is mandatory.  The f**2 scale-dependent-bias
  displacement variance can be logarithmically sensitive to the box/survey
  infrared cutoff for local PNG.
* Reconstruction shift noise is optional and off by default.  It is returned
  transparently in the same variance expansion when supplied.
* Stochastic source templates are returned separately from damping-induced
  mixing.  Combining them assumes the same alpha3 amplitude multiplies all
  finite-PNG orders and must be an explicit likelihood-level choice.
"""

