@dataclass(frozen=True)
class PostReconTreeIrResult:
    """Auditable post-reconstruction finite-PNG IR result."""

    deterministic: TreeComponents
    source_only: TreeComponents
    no_wiggle_source: TreeComponents
    damping_mixing: DampingMixing
    source_stochastic: StochasticBases
    stochastic_mixing: StochasticDampingMixing
    source_operator_terms: Mapping[str, float]
    displacement: DisplacementVarianceExpansion
    damping: LegDampingExpansion
    adaptive: AdaptiveReconstructionConfig
    mesh_damping: MeshDampingMode

    def __post_init__(self) -> None:
        missing = set(POST_ALL_TERMS).difference(self.source_operator_terms)
        if missing:
            raise ValueError(f"source_operator_terms missing {sorted(missing)}")
        frozen = MappingProxyType(
            {name: float(self.source_operator_terms[name]) for name in POST_ALL_TERMS}
        )
        object.__setattr__(self, "source_operator_terms", frozen)

    def predict_deterministic(self, fnl: float) -> float:
        return self.deterministic.predict(fnl)

    def stochastic_if_common_alpha3(self) -> StochasticBases:
        """Close damping mixing into alpha3 only under an explicit assumption.

        This is appropriate only if the likelihood uses one common alpha3
        amplitude for Gaussian, linear-PNG and quadratic-PNG orders.  The
        default result intentionally does not make that closure silently.
        """

        return StochasticBases(
            alpha3_gaussian=self.source_stochastic.alpha3_gaussian,
            alpha3_linear_png=(
                self.source_stochastic.alpha3_linear_png
                + self.stochastic_mixing.linear_from_gaussian_alpha3
            ),
            alpha3_quadratic_png=(
                self.source_stochastic.alpha3_quadratic_png
                + self.stochastic_mixing.quadratic_from_linear_alpha3
                + self.stochastic_mixing.quadratic_from_gaussian_alpha3
            ),
            alpha4_constant=self.source_stochastic.alpha4_constant,
        )


@dataclass(frozen=True)
class _IrGrid:
    q: NDArray[np.float64]
    p_nw: NDArray[np.float64]
    m_nw: NDArray[np.float64]
    shift_noise: NDArray[np.float64] | None


def _validate_1d(name: str, value: ArrayLike, *, positive: bool = False) -> NDArray[np.float64]:
    array = np.asarray(value, dtype=np.float64)
    if array.ndim != 1 or array.size < 3:
        raise ValueError(f"{name} must be a one-dimensional array with >=3 values")
    if not np.all(np.isfinite(array)):
        raise ValueError(f"{name} contains non-finite values")
    if positive and np.any(array <= 0.0):
        raise ValueError(f"{name} must be strictly positive")
    return array


def _interp_with_bounds(
    q: NDArray[np.float64],
    values: Sequence[NDArray[np.float64]],
    lower: float,
    upper: float,
) -> tuple[NDArray[np.float64], list[NDArray[np.float64]]]:
    if lower < q[0] or upper > q[-1]:
        raise ValueError(
            "the supplied q grid must bracket both q_min and k_ir "
            f"(grid=[{q[0]}, {q[-1]}], requested=[{lower}, {upper}])"
        )
    interior = q[(q > lower) & (q < upper)]
    bounded = np.concatenate(([lower], interior, [upper]))
    bounded = np.unique(bounded)
    if bounded.size < 3:
        raise ValueError("fewer than three q samples remain in [q_min,k_ir]")
    return bounded, [np.interp(bounded, q, item) for item in values]


def _prepare_ir_grid(
    q: ArrayLike,
    linear_power: ArrayLike,
    no_wiggle_power: ArrayLike,
    transfer_m: ArrayLike,
    settings: PostReconIrSettings,
    shift_noise_power: ShiftNoiseInput,
) -> _IrGrid:
    q_all = _validate_1d("q", q, positive=True)
    if np.any(np.diff(q_all) <= 0.0):
        raise ValueError("q must be strictly increasing")
    p_full = _validate_1d("linear_power_q", linear_power, positive=True)
    p_nw = _validate_1d("no_wiggle_power_q", no_wiggle_power, positive=True)
    m_full = _validate_1d("transfer_m_q", transfer_m, positive=True)
    for name, item in (
        ("linear_power_q", p_full),
        ("no_wiggle_power_q", p_nw),
        ("transfer_m_q", m_full),
    ):
        if item.shape != q_all.shape:
            raise ValueError(f"{name} must have the same shape as q")
    m_nw_all = m_full * np.sqrt(p_nw / p_full)

    noise_all: NDArray[np.float64] | None
    if shift_noise_power is None:
        noise_all = None
    elif callable(shift_noise_power):
        noise_all = np.asarray(shift_noise_power(q_all), dtype=np.float64)
    else:
        noise_all = np.asarray(shift_noise_power, dtype=np.float64)
    if noise_all is not None:
        if noise_all.shape != q_all.shape:
            raise ValueError("shift_noise_power must have the same shape as q")
        if not np.all(np.isfinite(noise_all)) or np.any(noise_all < 0.0):
            raise ValueError("shift_noise_power must be finite and non-negative")

    arrays = [p_nw, m_nw_all]
    if noise_all is not None:
        arrays.append(noise_all)
    q_used, sampled = _interp_with_bounds(
        q_all, arrays, settings.q_min, settings.k_ir
    )
    return _IrGrid(
        q=q_used,
        p_nw=sampled[0],
        m_nw=sampled[1],
        shift_noise=sampled[2] if noise_all is not None else None,
    )


def _mesh_active(reconstruction: ReconstructionConfig) -> bool:
    return reconstruction.cell_size > 0.0 and reconstruction.cic_window_power > 0


def _resolved_mesh_mode(
    settings: PostReconIrSettings,
    reconstruction: ReconstructionConfig,
) -> MeshDampingMode:
    if settings.mesh_damping == "auto":
        return "cartesian" if _mesh_active(reconstruction) else "isotropic"
    if settings.mesh_damping == "isotropic" and _mesh_active(reconstruction):
        raise ValueError(
            "isotropic damping would silently discard the active Cartesian CIC "
            "window; use mesh_damping='cartesian' or disable CIC"
        )
    return settings.mesh_damping


def _residual_coefficients(
    window: NDArray[np.float64] | float,
    inverse_m: float,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> tuple[NDArray[np.float64], NDArray[np.float64], NDArray[np.float64]]:
    """Return C(f)^2 coefficients c0,c1,c2 at fixed q/direction."""

    w = np.asarray(window, dtype=np.float64)
    b = reconstruction.bias_recon
    eta = adaptive.eta
    a = bias.b1 / b
    n = bias.bphi * inverse_m / b
    d = adaptive.bphi_recon * inverse_m / b

    r0 = 1.0 - w * a
    r1 = -w * (n - eta * a * d)
    r2 = w * (eta * n * d - eta**2 * a * d**2)
    c0 = r0**2
    c1 = 2.0 * r0 * r1
    c2 = r1**2 + 2.0 * r0 * r2
    return c0, c1, c2


def _noise_coefficients(
    window: NDArray[np.float64] | float,
    inverse_m: float,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> tuple[NDArray[np.float64], NDArray[np.float64], NDArray[np.float64]]:
    """Return W^2/b_rec(f)^2 coefficients for uncorrelated shift noise."""

    w = np.asarray(window, dtype=np.float64)
    b = reconstruction.bias_recon
    d = adaptive.bphi_recon * inverse_m / b
    eta = adaptive.eta
    base = w**2 / b**2
    return base, -2.0 * eta * d * base, 3.0 * eta**2 * d**2 * base


def _isotropic_variance_coefficients(
    grid: _IrGrid,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
    settings: PostReconIrSettings,
) -> tuple[float, float, float]:
    q = grid.q
    smoothing = np.exp(-0.5 * (q * reconstruction.smoothing_radius) ** 2)
    inverse_m = 1.0 / grid.m_nw
    coefficients = [np.zeros_like(q) for _ in range(3)]

    for index in range(q.size):
        c0, c1, c2 = _residual_coefficients(
            float(smoothing[index]),
            float(inverse_m[index]),
            bias,
            reconstruction,
            adaptive,
        )
        coefficients[0][index] = grid.p_nw[index] * float(c0)
        coefficients[1][index] = grid.p_nw[index] * float(c1)
        coefficients[2][index] = grid.p_nw[index] * float(c2)
        if grid.shift_noise is not None:
            n0, n1, n2 = _noise_coefficients(
                float(smoothing[index]),
                float(inverse_m[index]),
                reconstruction,
                adaptive,
            )
            coefficients[0][index] += grid.shift_noise[index] * float(n0)
            coefficients[1][index] += grid.shift_noise[index] * float(n1)
            coefficients[2][index] += grid.shift_noise[index] * float(n2)

    x = q * settings.r_bao
    bao_window = 1.0 - spherical_jn(0, x) + 2.0 * spherical_jn(2, x)
    prefactor = bao_window / (6.0 * math.pi**2)
    return tuple(
        float(simpson(item * prefactor, x=q)) for item in coefficients
    )  # type: ignore[return-value]


def _angular_grid(mu_order: int, phi_order: int) -> tuple[NDArray[np.float64], NDArray[np.float64]]:
    mu, w_mu = leggauss(mu_order)
    phi = 2.0 * math.pi * np.arange(phi_order, dtype=np.float64) / phi_order
    sin_theta = np.sqrt(np.maximum(0.0, 1.0 - mu**2))
    qhat = np.stack(
        (
            (sin_theta[:, None] * np.cos(phi)[None, :]).ravel(),
            (sin_theta[:, None] * np.sin(phi)[None, :]).ravel(),
            np.broadcast_to(mu[:, None], (mu_order, phi_order)).ravel(),
        ),
        axis=1,
    )
    weights = np.broadcast_to(
        w_mu[:, None] * (2.0 * math.pi / phi_order),
        (mu_order, phi_order),
    ).ravel()
    return qhat, weights


def _cartesian_cic_window(
    q_vectors: NDArray[np.float64],
    reconstruction: ReconstructionConfig,
) -> NDArray[np.float64]:
    if not _mesh_active(reconstruction):
        return np.ones(q_vectors.shape[0], dtype=np.float64)
    arguments = q_vectors * reconstruction.cell_size / (2.0 * math.pi)
    product = np.prod(np.sinc(arguments), axis=1)
    return product ** reconstruction.cic_window_power


def _cartesian_variance_coefficients(
    vectors: NDArray[np.float64],
    grid: _IrGrid,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
    settings: PostReconIrSettings,
) -> tuple[tuple[float, float, float], tuple[float, float, float], tuple[float, float, float]]:
    qhat, angular_weights = _angular_grid(
        settings.angular_mu_order, settings.angular_phi_order
    )
    khat = vectors / np.linalg.norm(vectors, axis=1)[:, None]
    mu_leg = khat @ qhat.T
    radial = np.zeros((3, 3, grid.q.size), dtype=np.float64)
    angular_prefactor = 1.0 / (2.0 * math.pi) ** 3

    for q_index, q_value in enumerate(grid.q):
        q_vectors = q_value * qhat
        mesh = _cartesian_cic_window(q_vectors, reconstruction)
        smoothing = math.exp(
            -0.5 * (q_value * reconstruction.smoothing_radius) ** 2
        )
        window = smoothing * mesh
        inverse_m = 1.0 / grid.m_nw[q_index]
        c = _residual_coefficients(
            window, inverse_m, bias, reconstruction, adaptive
        )
        if grid.shift_noise is not None:
            noise = _noise_coefficients(
                window, inverse_m, reconstruction, adaptive
            )
        else:
            noise = None

        for leg in range(3):
            mu = mu_leg[leg]
            bao_kernel = mu**2 * (
                1.0 - np.cos(q_value * settings.r_bao * mu)
            )
            weighted_kernel = angular_weights * bao_kernel
            for order in range(3):
                spectrum = grid.p_nw[q_index] * c[order]
                if noise is not None:
                    spectrum = spectrum + grid.shift_noise[q_index] * noise[order]
                radial[leg, order, q_index] = (
                    angular_prefactor
                    * float(np.sum(weighted_kernel * spectrum))
                )

    integrated = np.empty((3, 3), dtype=np.float64)
    for leg in range(3):
        for order in range(3):
            integrated[leg, order] = float(
                simpson(radial[leg, order], x=grid.q)
            )
    return (
        tuple(float(value) for value in integrated[:, 0]),
        tuple(float(value) for value in integrated[:, 1]),
        tuple(float(value) for value in integrated[:, 2]),
    )


def post_recon_displacement_variance_expansion(
    vectors: ArrayLike,
    q: ArrayLike,
    linear_power_q: ArrayLike,
    no_wiggle_power_q: ArrayLike,
    transfer_m_q: ArrayLike,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    settings: PostReconIrSettings,
    adaptive: AdaptiveReconstructionConfig | None = None,
    *,
    shift_noise_power: ShiftNoiseInput = None,
) -> DisplacementVarianceExpansion:
    """Compute ``Sigma_rec^2(f)=S0+f*S1+f**2*S2`` for each leg.

    With no Cartesian mesh window the result is isotropic and the same scalar
    is repeated for all three external legs.  With CIC, the angular integral
    is evaluated in the actual grid frame for every external leg.
    """

    kvec = _closed_vectors(vectors)
    adaptive_config = adaptive or AdaptiveReconstructionConfig()
    grid = _prepare_ir_grid(
        q,
        linear_power_q,
        no_wiggle_power_q,
        transfer_m_q,
        settings,
        shift_noise_power,
    )
    mode = _resolved_mesh_mode(settings, reconstruction)
    if mode == "isotropic":
        values = _isotropic_variance_coefficients(
            grid, bias, reconstruction, adaptive_config, settings
        )
        sigma0 = (values[0],) * 3
        sigma1 = (values[1],) * 3
        sigma2 = (values[2],) * 3
        anisotropic = False
    else:
        sigma0, sigma1, sigma2 = _cartesian_variance_coefficients(
            kvec,
            grid,
            bias,
            reconstruction,
            adaptive_config,
            settings,
        )
        anisotropic = True

    sigma0 = tuple(max(0.0, value) if value > -1.0e-12 else value for value in sigma0)
    return DisplacementVarianceExpansion(
        sigma_f0=sigma0,
        sigma_f1=sigma1,
        sigma_f2=sigma2,
        anisotropic=anisotropic,
        q_min=settings.q_min,
        k_ir=settings.k_ir,
        includes_shift_noise=shift_noise_power is not None,
    )


def _exact_residual_squared(
    window: NDArray[np.float64] | float,
    inverse_m: float,
    fnl: float,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> NDArray[np.float64]:
    denominator = reconstruction.bias_recon + (
        adaptive.eta * fnl * adaptive.bphi_recon * inverse_m
    )
    if abs(denominator) <= 1.0e-14:
        raise ValueError("adaptive reconstruction denominator crosses zero")
    numerator = bias.b1 + fnl * bias.bphi * inverse_m
    return (1.0 - np.asarray(window) * numerator / denominator) ** 2


def _exact_noise_factor(
    window: NDArray[np.float64] | float,
    inverse_m: float,
    fnl: float,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> NDArray[np.float64]:
    denominator = reconstruction.bias_recon + (
        adaptive.eta * fnl * adaptive.bphi_recon * inverse_m
    )
    if abs(denominator) <= 1.0e-14:
        raise ValueError("adaptive reconstruction denominator crosses zero")
    return np.asarray(window) ** 2 / denominator**2


def post_recon_displacement_variance_at_fnl(
    vectors: ArrayLike,
    q: ArrayLike,
    linear_power_q: ArrayLike,
    no_wiggle_power_q: ArrayLike,
    transfer_m_q: ArrayLike,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    settings: PostReconIrSettings,
    fnl: float,
    adaptive: AdaptiveReconstructionConfig | None = None,
    *,
    shift_noise_power: ShiftNoiseInput = None,
) -> tuple[float, float, float]:
    """Direct finite-``fNL`` displacement variance for regression tests.

    This function does not truncate the adaptive denominator.  It is intended
    to validate ``S0/S1/S2`` by finite differences and to diagnose the radius
    of validity of the quadratic expansion.
    """

    value = float(fnl)
    if not math.isfinite(value):
        raise ValueError("fnl must be finite")
    kvec = _closed_vectors(vectors)
    adaptive_config = adaptive or AdaptiveReconstructionConfig()
    grid = _prepare_ir_grid(
        q,
        linear_power_q,
        no_wiggle_power_q,
        transfer_m_q,
        settings,
        shift_noise_power,
    )
    mode = _resolved_mesh_mode(settings, reconstruction)

    if mode == "isotropic":
        smoothing = np.exp(-0.5 * (grid.q * reconstruction.smoothing_radius) ** 2)
        spectra = np.empty_like(grid.q)
        for index in range(grid.q.size):
            inv_m = 1.0 / grid.m_nw[index]
            spectra[index] = grid.p_nw[index] * float(
                _exact_residual_squared(
                    smoothing[index],
                    inv_m,
                    value,
                    bias,
                    reconstruction,
                    adaptive_config,
                )
            )
            if grid.shift_noise is not None:
                spectra[index] += grid.shift_noise[index] * float(
                    _exact_noise_factor(
                        smoothing[index],
                        inv_m,
                        value,
                        reconstruction,
                        adaptive_config,
                    )
                )
        x = grid.q * settings.r_bao
        kernel = 1.0 - spherical_jn(0, x) + 2.0 * spherical_jn(2, x)
        sigma = float(
            simpson(spectra * kernel / (6.0 * math.pi**2), x=grid.q)
        )
        return (max(0.0, sigma),) * 3

    qhat, angular_weights = _angular_grid(
        settings.angular_mu_order, settings.angular_phi_order
    )
    khat = kvec / np.linalg.norm(kvec, axis=1)[:, None]
    mu_leg = khat @ qhat.T
    radial = np.zeros((3, grid.q.size), dtype=np.float64)
    angular_prefactor = 1.0 / (2.0 * math.pi) ** 3
    for q_index, q_value in enumerate(grid.q):
        q_vectors = q_value * qhat
        window = math.exp(
            -0.5 * (q_value * reconstruction.smoothing_radius) ** 2
        ) * _cartesian_cic_window(q_vectors, reconstruction)
        inv_m = 1.0 / grid.m_nw[q_index]
        spectrum = grid.p_nw[q_index] * _exact_residual_squared(
            window,
            inv_m,
            value,
            bias,
            reconstruction,
            adaptive_config,
        )
        if grid.shift_noise is not None:
            spectrum = spectrum + grid.shift_noise[q_index] * _exact_noise_factor(
                window,
                inv_m,
                value,
                reconstruction,
                adaptive_config,
            )
        for leg in range(3):
            mu = mu_leg[leg]
            kernel = mu**2 * (
                1.0 - np.cos(q_value * settings.r_bao * mu)
            )
            radial[leg, q_index] = angular_prefactor * float(
                np.sum(angular_weights * kernel * spectrum)
            )
    return tuple(
        max(0.0, float(simpson(radial[leg], x=grid.q)))
        for leg in range(3)
    )


def damping_expansion_from_variance(
    vectors: ArrayLike,
    displacement: DisplacementVarianceExpansion,
) -> LegDampingExpansion:
    """Convert per-leg variance coefficients into damping coefficients."""

    kvec = _closed_vectors(vectors)
    k = np.linalg.norm(kvec, axis=1)
    s0 = np.asarray(displacement.sigma_f0)
    s1 = np.asarray(displacement.sigma_f1)
    s2 = np.asarray(displacement.sigma_f2)
    D0 = np.exp(-k**2 * s0)
    d1 = -k**2 * s1
    d2 = 0.5 * k**4 * s1**2 - k**2 * s2
    return LegDampingExpansion(
        D0=tuple(float(item) for item in D0),
        d1=tuple(float(item) for item in d1),
        d2=tuple(float(item) for item in d2),
    )


def _adaptive_source_terms_raw(
    kvec: NDArray[np.float64],
    power: Sequence[Scalar],
    transfer: Sequence[Scalar],
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> dict[str, Scalar]:
    """Native adaptive-denominator tree bases with physical prefactors."""

    terms: dict[str, Scalar] = {
        name: 0.0 for name in ADAPTIVE_LINEAR_TERMS + ADAPTIVE_QUADRATIC_TERMS
    }
    eta = adaptive.eta
    if eta == 0.0 or adaptive.bphi_recon == 0.0:
        return terms

    ratio = adaptive.bphi_recon / reconstruction.bias_recon
    inverse_m: list[Scalar] = [1.0 / item for item in transfer]
    for i, j in ((0, 1), (1, 2), (2, 0)):
        total = kvec[i] + kvec[j]
        shift_i = _shift_factor(total, kvec[i], reconstruction)
        shift_j = _shift_factor(total, kvec[j], reconstruction)
        pp = power[i] * power[j]
        ui = inverse_m[i]
        uj = inverse_m[j]
        shift_over_m = shift_i * ui + shift_j * uj

        gaussian_linear: Scalar = -pp * shift_over_m
        gaussian_quadratic: Scalar = pp * (
            shift_i * ui**2 + shift_j * uj**2
        )
        png_linear_cross: Scalar = (
            -2.0 * pp * (ui + uj) * shift_over_m
        )

        terms["dBdfNL_rec_brec_gaussian_linear"] += (
            eta * bias.b1**4 * ratio * gaussian_linear
        )
        terms["Btree_fNL2_rec_brec_gaussian_quadratic"] += (
            eta**2 * bias.b1**4 * ratio**2 * gaussian_quadratic
        )
        terms["Btree_fNL2_rec_brec_png_linear_cross"] += (
            eta
            * bias.b1**3
            * bias.bphi
            * ratio
            * png_linear_cross
        )
    return terms


def _post_source_terms_raw(
    kvec: NDArray[np.float64],
    power: Sequence[Scalar],
    transfer: Sequence[Scalar],
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
) -> dict[str, Scalar]:
    terms = dict(
        _finite_png_halo_tree_terms_raw(
            kvec, power, transfer, bias, reconstruction
        )
    )
    terms.update(
        _adaptive_source_terms_raw(
            kvec,
            power,
            transfer,
            bias,
            reconstruction,
            adaptive,
        )
    )
    return terms


def post_recon_source_operator_terms(
    vectors: ArrayLike,
    linear_power: ArrayLike,
    transfer_m: ArrayLike,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig | None = None,
) -> dict[str, float]:
    """Return fixed-order post-reconstruction source terms through fNL**2."""

    kvec = _closed_vectors(vectors)
    power = _vector3(linear_power, "linear_power", positive=True)
    transfer = _vector3(transfer_m, "transfer_m", positive=True)
    config = adaptive or AdaptiveReconstructionConfig()
    return _values(
        _post_source_terms_raw(
            kvec,
            power.tolist(),
            transfer.tolist(),
            bias,
            reconstruction,
            config,
        )
    )


def _components_from_post_terms(terms: Mapping[str, float]) -> TreeComponents:
    return TreeComponents(
        gaussian=sum(terms[name] for name in POST_GAUSSIAN_TERMS),
        linear=sum(terms[name] for name in POST_LINEAR_TERMS),
        quadratic=sum(terms[name] for name in POST_QUADRATIC_TERMS),
    )


def _stochastic_from_post_terms(terms: Mapping[str, float]) -> StochasticBases:
    return StochasticBases(
        alpha3_gaussian=terms["stochastic_alpha3_basis"],
        alpha3_linear_png=terms["dBdfNL_stochastic_alpha3_basis"],
        alpha3_quadratic_png=terms[
            "Bhalo_tree_fNL2_stochastic_alpha3PNG_basis"
        ],
        alpha4_constant=terms["stochastic_alpha4_basis"],
    )


def _strict_post_leg_response(
    kvec: NDArray[np.float64],
    smooth_power: NDArray[np.float64],
    wiggle_power: NDArray[np.float64],
    smooth_transfer: NDArray[np.float64],
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    adaptive: AdaptiveReconstructionConfig,
    leg: int,
) -> dict[str, float]:
    power: list[Scalar] = [float(item) for item in smooth_power]
    transfer: list[Scalar] = [float(item) for item in smooth_transfer]
    power[leg] = _Dual(smooth_power[leg], wiggle_power[leg])
    transfer[leg] = _Dual(
        smooth_transfer[leg],
        0.5
        * smooth_transfer[leg]
        * wiggle_power[leg]
        / smooth_power[leg],
    )
    return _tangents(
        _post_source_terms_raw(
            kvec,
            power,
            transfer,
            bias,
            reconstruction,
            adaptive,
        )
    )


def _group_leg_response(response: Mapping[str, float]) -> tuple[float, float, float]:
    return (
        sum(response[name] for name in POST_GAUSSIAN_TERMS),
        sum(response[name] for name in POST_LINEAR_TERMS),
        sum(response[name] for name in POST_QUADRATIC_TERMS),
    )


def ir_resummed_post_recon_finite_png_tree(
    vectors: ArrayLike,
    linear_power: ArrayLike,
    no_wiggle_power: ArrayLike,
    transfer_m: ArrayLike,
    bias: HaloTreeBias,
    reconstruction: ReconstructionConfig,
    q: ArrayLike,
    linear_power_q: ArrayLike,
    no_wiggle_power_q: ArrayLike,
    transfer_m_q: ArrayLike,
    settings: PostReconIrSettings,
    adaptive: AdaptiveReconstructionConfig | None = None,
    *,
    shift_noise_power: ShiftNoiseInput = None,
) -> PostReconTreeIrResult:
    """Strict leading-wiggle post-reconstruction IR resummation.

    The source and damping exponent are both expanded consistently through
    ``fNL**2``.  IR resummation is performed for every Cartesian triangle
    before any shell or orientation average.
    """

    kvec = _closed_vectors(vectors)
    full_power = _vector3(linear_power, "linear_power", positive=True)
    smooth_power = _vector3(no_wiggle_power, "no_wiggle_power", positive=True)
    full_transfer = _vector3(transfer_m, "transfer_m", positive=True)
    smooth_transfer = no_wiggle_transfer(
        full_power, smooth_power, full_transfer
    )
    wiggle_power = full_power - smooth_power
    adaptive_config = adaptive or AdaptiveReconstructionConfig()

    displacement = post_recon_displacement_variance_expansion(
        kvec,
        q,
        linear_power_q,
        no_wiggle_power_q,
        transfer_m_q,
        bias,
        reconstruction,
        settings,
        adaptive_config,
        shift_noise_power=shift_noise_power,
    )
    damping = damping_expansion_from_variance(kvec, displacement)

    no_wiggle_terms = _values(
        _post_source_terms_raw(
            kvec,
            smooth_power.tolist(),
            smooth_transfer.tolist(),
            bias,
            reconstruction,
            adaptive_config,
        )
    )
    source_terms = {name: float(no_wiggle_terms[name]) for name in POST_ALL_TERMS}
    leg_responses: list[dict[str, float]] = []
    grouped_responses: list[tuple[float, float, float]] = []
    for leg in range(3):
        response = _strict_post_leg_response(
            kvec,
            smooth_power,
            wiggle_power,
            smooth_transfer,
            bias,
            reconstruction,
            adaptive_config,
            leg,
        )
        leg_responses.append(response)
        grouped_responses.append(_group_leg_response(response))
        for name in POST_ALL_TERMS:
            source_terms[name] += damping.D0[leg] * response[name]

    no_wiggle_components = _components_from_post_terms(no_wiggle_terms)
    source_components = _components_from_post_terms(source_terms)

    linear_from_gaussian = sum(
        damping.D0[leg]
        * damping.d1[leg]
        * grouped_responses[leg][0]
        for leg in range(3)
    )
    quadratic_from_linear = sum(
        damping.D0[leg]
        * damping.d1[leg]
        * grouped_responses[leg][1]
        for leg in range(3)
    )
    quadratic_from_gaussian = sum(
        damping.D0[leg]
        * damping.d2[leg]
        * grouped_responses[leg][0]
        for leg in range(3)
    )
    deterministic_mixing = DampingMixing(
        linear_from_gaussian=linear_from_gaussian,
        quadratic_from_linear=quadratic_from_linear,
        quadratic_from_gaussian=quadratic_from_gaussian,
    )
    deterministic = TreeComponents(
        gaussian=source_components.gaussian,
        linear=source_components.linear + linear_from_gaussian,
        quadratic=(
            source_components.quadratic
            + quadratic_from_linear
            + quadratic_from_gaussian
        ),
    )

    stochastic_source = _stochastic_from_post_terms(source_terms)
    stochastic_mixing = StochasticDampingMixing(
        linear_from_gaussian_alpha3=sum(
            damping.D0[leg]
            * damping.d1[leg]
            * leg_responses[leg]["stochastic_alpha3_basis"]
            for leg in range(3)
        ),
        quadratic_from_linear_alpha3=sum(
            damping.D0[leg]
            * damping.d1[leg]
            * leg_responses[leg]["dBdfNL_stochastic_alpha3_basis"]
            for leg in range(3)
        ),
        quadratic_from_gaussian_alpha3=sum(
            damping.D0[leg]
            * damping.d2[leg]
            * leg_responses[leg]["stochastic_alpha3_basis"]
            for leg in range(3)
        ),
    )

    return PostReconTreeIrResult(
        deterministic=deterministic,
        source_only=source_components,
        no_wiggle_source=no_wiggle_components,
        damping_mixing=deterministic_mixing,
        source_stochastic=stochastic_source,
        stochastic_mixing=stochastic_mixing,
        source_operator_terms=source_terms,
        displacement=displacement,
        damping=damping,
        adaptive=adaptive_config,
        mesh_damping=_resolved_mesh_mode(settings, reconstruction),
    )
