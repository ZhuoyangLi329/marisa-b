@dataclass(frozen=True)
class AdaptiveReconstructionConfig:
    """Finite-PNG reconstruction-denominator settings.

    The physical bispectrum parameter is denoted ``f``.  The reconstruction
    catalogue/algorithm can use ``f_rec = fnl_recon_ratio * f``.

    Common choices
    --------------
    * ``fnl_recon_ratio=0``: current fixed-``b_rec`` reconstruction.
    * ``fnl_recon_ratio=1`` and ``bphi_recon=bphi``: matched adaptive
      denominator.
    * Other finite ratios: controlled stress tests or deliberately mismatched
      reconstruction.
    """

    bphi_recon: float = 0.0
    fnl_recon_ratio: float = 0.0

    def __post_init__(self) -> None:
        for field in fields(self):
            value = float(getattr(self, field.name))
            if not math.isfinite(value):
                raise ValueError(f"{field.name} must be finite")
            object.__setattr__(self, field.name, value)

    @property
    def eta(self) -> float:
        return self.fnl_recon_ratio


@dataclass(frozen=True)
class PostReconIrSettings:
    """Numerical and physical settings for post-reconstruction damping.

    ``q_min`` is not a mere integration convenience.  For local PNG it is the
    finite-box/survey infrared cutoff used by the reconstruction displacement
    model and should be registered in the analysis provenance.
    """

    r_bao: float
    k_ir: float
    q_min: float
    mesh_damping: MeshDampingMode = "auto"
    angular_mu_order: int = 32
    angular_phi_order: int = 64

    def __post_init__(self) -> None:
        for name in ("r_bao", "k_ir", "q_min"):
            value = float(getattr(self, name))
            if not math.isfinite(value) or value <= 0.0:
                raise ValueError(f"{name} must be finite and positive")
            object.__setattr__(self, name, value)
        if self.q_min >= self.k_ir:
            raise ValueError("q_min must be smaller than k_ir")
        if self.mesh_damping not in {"auto", "isotropic", "cartesian"}:
            raise ValueError(f"unsupported mesh_damping={self.mesh_damping!r}")
        for name in ("angular_mu_order", "angular_phi_order"):
            value = int(getattr(self, name))
            if value != getattr(self, name) or value < 4:
                raise ValueError(f"{name} must be an integer >= 4")
            object.__setattr__(self, name, value)


@dataclass(frozen=True)
class DisplacementVarianceExpansion:
    """Per-leg coefficients of ``Sigma_rec^2(f)`` through ``f**2``."""

    sigma_f0: tuple[float, float, float]
    sigma_f1: tuple[float, float, float]
    sigma_f2: tuple[float, float, float]
    anisotropic: bool
    q_min: float
    k_ir: float
    includes_shift_noise: bool

    def __post_init__(self) -> None:
        for name in ("sigma_f0", "sigma_f1", "sigma_f2"):
            values = tuple(float(value) for value in getattr(self, name))
            if len(values) != 3 or not all(math.isfinite(value) for value in values):
                raise ValueError(f"{name} must contain three finite values")
            object.__setattr__(self, name, values)
        if any(value < -1.0e-12 for value in self.sigma_f0):
            raise ValueError("the Gaussian displacement variance is negative")


@dataclass(frozen=True)
class LegDampingExpansion:
    """Per-leg damping coefficients.

    ``D(f)=D0*(1+f*d1+f**2*d2)+O(f**3)``.
    """

    D0: tuple[float, float, float]
    d1: tuple[float, float, float]
    d2: tuple[float, float, float]

    def __post_init__(self) -> None:
        for name in ("D0", "d1", "d2"):
            values = tuple(float(value) for value in getattr(self, name))
            if len(values) != 3 or not all(math.isfinite(value) for value in values):
                raise ValueError(f"{name} must contain three finite values")
            object.__setattr__(self, name, values)
        if not all(0.0 <= value <= 1.0 + 1.0e-14 for value in self.D0):
            raise ValueError("D0 must lie in [0,1]")


@dataclass(frozen=True)
class DampingMixing:
    """Deterministic finite-PNG terms generated by the damping exponent."""

    linear_from_gaussian: float
    quadratic_from_linear: float
    quadratic_from_gaussian: float

    def __post_init__(self) -> None:
        for field in fields(self):
            value = float(getattr(self, field.name))
            if not math.isfinite(value):
                raise ValueError(f"{field.name} must be finite")
            object.__setattr__(self, field.name, value)

    @property
    def total_quadratic(self) -> float:
        return self.quadratic_from_linear + self.quadratic_from_gaussian


