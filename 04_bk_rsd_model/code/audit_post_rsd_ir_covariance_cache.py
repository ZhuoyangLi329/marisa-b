"""模块大纲：实际冻结谱上的旧/新SciPy回归与精确长位移缓存验证。

legacy-reference必须使用仍有原sph_harm的既有环境；compare使用生产环境。
只验收球谐API和协方差缓存，不认证全44-bin IR-B、STO随机项或主MCMC。
"""
import os
for name in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS', 'NUMEXPR_NUM_THREADS'):
    os.environ[name] = '1'
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import platform
import time
import numpy as np
import scipy
from scipy import special
from rsd_b000_contract import PART, F_GROWTH, digest
from post_rsd_ir_inputs import ROOT, FrozenIRSpectra, frozen_reconstruction
from post_rsd_fixedrec import pbs_bias

OUT = ROOT/'ir_covariance_cache_validation'


def save(path, value):
    with path.open('x') as stream:
        json.dump(value, stream, indent=2, allow_nan=False); stream.write('\n')


def legacy_reference():
    if not hasattr(special, 'sph_harm'):
        raise ValueError('must use original existing legacy SciPy, without bridge')
    if getattr(special.sph_harm, '__module__', '') == 'post_rsd_scipy_harmonic_compat':
        raise ValueError('reference must not be generated by the compatibility bridge')
    from post_rsd_ir_harmonics import HarmonicDisplacement, even_harmonics
    if OUT.exists():
        raise ValueError('preserve existing reference/cache audit')
    spectrum = FrozenIRSpectra(); rec = frozen_reconstruction(256); long = spectrum.long_modes(513)
    rng = np.random.default_rng(202610100135)
    directions = np.vstack((np.eye(3), -np.eye(3), rng.normal(size=(58, 3))))
    directions /= np.linalg.norm(directions, axis=1)[:, None]
    b, p = 2.11, 1.417; phi = pbs_bias(b, p_halo=p).bphi
    h = HarmonicDisplacement.from_long_modes(long, lmax=10, b1=b, bphi=phi,
        f_growth=F_GROWTH, los=(0, 0, 1), reconstruction=rec)
    vectors = directions*.075; y, ell = even_harmonics(directions, 10)
    OUT.mkdir()
    target = OUT/'LEGACY_REFERENCE.npz'
    np.savez_compressed(target, vectors=vectors, harmonics=y, degrees=ell,
        coefficients=h.coefficients, covariance=h.covariance(vectors), damping=h.damping(vectors))
    save(OUT/'LEGACY_REFERENCE.json', dict(status='ORIGINAL_LEGACY_HARMONIC_REFERENCE_NOT_IR_MODEL_ACCEPTANCE',
        created_UTC=datetime.now(timezone.utc).isoformat(), scipy_version=scipy.__version__,
        python_version=platform.python_version(), spectrum=spectrum.provenance,
        physical_parameters=h.physical_parameters, probe_b1=b, probe_p_halo=p,
        p_probe_not_calibrated=True, reference_sha256=digest(target),
        original_harmonic_source_sha256=digest(PART/'code/post_rsd_ir_harmonics.py'),
        entry_sha256=digest(Path(__file__)), CPU_affinity=sorted(os.sched_getaffinity(0)),
        full44_IR_B_verified=False, actual_STO_noise_validated=False, MCMC_released=False))
    print('ORIGINAL_LEGACY_REFERENCE_SAVED', flush=True)


def compare():
    from post_rsd_scipy_harmonic_compat import install_legacy_sph_harm
    compatibility = install_legacy_sph_harm()
    from post_rsd_ir_harmonics import HarmonicDisplacement, even_harmonics
    from post_rsd_ir_covariance_basis import HarmonicCovarianceBasis
    target = OUT/'PRODUCTION_COMPAT_AND_CACHE_AUDIT.json'
    if target.exists():
        raise ValueError('preserve existing comparison audit')
    meta = json.loads((OUT/'LEGACY_REFERENCE.json').read_text())
    reference = OUT/'LEGACY_REFERENCE.npz'
    if digest(reference) != meta['reference_sha256']:
        raise ValueError('legacy reference bytes drift')
    if digest(PART/'code/post_rsd_ir_harmonics.py') != meta['original_harmonic_source_sha256']:
        raise ValueError('original frozen harmonic source changed')
    spectrum = FrozenIRSpectra(); rec = frozen_reconstruction(256); long = spectrum.long_modes(513)
    if spectrum.provenance != meta['spectrum']:
        raise ValueError('old/new environment spectrum provenance differs')
    with np.load(reference, allow_pickle=False) as z:
        legacy = {k: np.array(z[k]) for k in z.files}
    b, p = meta['probe_b1'], meta['probe_p_halo']; phi = pbs_bias(b, p_halo=p).bphi
    kwargs = dict(f_growth=F_GROWTH, los=(0, 0, 1), reconstruction=rec, lmax=10)
    fresh = HarmonicDisplacement.from_long_modes(long, b1=b, bphi=phi, **kwargs)
    y, ell = even_harmonics(legacy['vectors'], 10); np.testing.assert_array_equal(ell, legacy['degrees'])
    outputs = dict(harmonics=y, coefficients=fresh.coefficients,
                   covariance=fresh.covariance(legacy['vectors']), damping=fresh.damping(legacy['vectors']))
    errors = {}
    for name, value in outputs.items():
        scale = max(1., float(np.max(np.abs(legacy[name]))))
        errors[name] = float(np.max(np.abs(value-legacy[name]))/scale)
    start = time.perf_counter(); basis = HarmonicCovarianceBasis.from_long_modes(long, **kwargs)
    build_seconds = time.perf_counter()-start; rows = []
    for b in (.5, 2.2280546353635335, 4.):
        for p in (0., 1.417, 3.):
            phi = pbs_bias(b, p_halo=p).bphi
            start = time.perf_counter()
            direct = HarmonicDisplacement.from_long_modes(long, b1=b, bphi=phi, **kwargs)
            direct_seconds = time.perf_counter()-start
            start = time.perf_counter(); cached = basis.harmonics_at(b1=b, bphi=phi)
            cache_seconds = time.perf_counter()-start
            scale = max(1., float(np.max(np.abs(direct.coefficients))))
            cerror = float(np.max(np.abs(cached.coefficients-direct.coefficients))/scale)
            a = cached.covariance(legacy['vectors']); minimum = None
            for fnl in (-500., 0., 500.):
                full = a[:, 0]+fnl*a[:, 1]+fnl*fnl*a[:, 2]
                eigen = float(np.linalg.eigvalsh(full).min())
                tolerance = 1e-10*max(1., float(np.max(np.abs(full))))
                if eigen < -tolerance:
                    raise ValueError('full physical covariance not PSD; no clipping or eigenvalue floor')
                minimum = eigen if minimum is None else min(minimum, eigen)
            dref = direct.damping(legacy['vectors']); dcache = cached.damping(legacy['vectors'])
            derror = float(np.max(np.abs(dcache-dref))/max(1., float(np.max(np.abs(dref)))))
            rows.append(dict(b1=b, physical_p_probe=p, coefficient_scaled_error=cerror,
                damping_scaled_error=derror, minimum_full_covariance_eigenvalue=minimum,
                direct_harmonic_build_seconds=direct_seconds, cached_coefficient_assembly_seconds=cache_seconds))
    tolerance = 2e-10
    maximum = max(list(errors.values())+[max(r['coefficient_scaled_error'], r['damping_scaled_error']) for r in rows])
    passed = maximum <= tolerance
    report = dict(status='ACTUAL_SPECTRUM_HARMONIC_COMPAT_AND_EXACT_BIAS_CACHE_PASS_NOT_FULL_IR_MODEL' if passed
        else 'REQUIRES_INVESTIGATION', created_UTC=datetime.now(timezone.utc).isoformat(),
        compatibility=compatibility, legacy_scipy_version=meta['scipy_version'],
        cross_environment_scaled_errors=errors, rows=rows, maximum_scaled_error=maximum,
        original_scaled_tolerance=tolerance, covariance_basis_build_seconds=build_seconds,
        coefficient_assembly_speedup_median=float(np.median([r['direct_harmonic_build_seconds']/r['cached_coefficient_assembly_seconds'] for r in rows])),
        speedup_scope='only harmonic coefficient assembly; not projected IR-B or MCMC runtime',
        signal_B_quartic_polynomial_assumed=False, old_IR_formulas_changed=False,
        negative_truncated_damping_issue_repaired=False, physical_p_calibrated=False,
        full44_IR_B_verified=False, actual_STO_noise_validated=False, MCMC_released=False,
        source_sha256=digest(Path(__file__)), reference_sha256=digest(reference), spectrum=spectrum.provenance,
        new_sources={name:digest(PART/'code'/name) for name in ('post_rsd_scipy_harmonic_compat.py', 'post_rsd_ir_covariance_basis.py')},
        CPU_affinity=sorted(os.sched_getaffinity(0)), python_version=platform.python_version())
    save(target, report)
    print(json.dumps({k:v for k,v in report.items() if k not in ('rows', 'spectrum')}, indent=2), flush=True)
    if not passed:
        raise SystemExit(1)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__); ap.add_argument('command', choices=('legacy-reference', 'compare'))
    args = ap.parse_args()
    if len(os.sched_getaffinity(0)) != 1:
        raise ValueError('one logical core for this bounded covariance audit')
    legacy_reference() if args.command == 'legacy-reference' else compare()
