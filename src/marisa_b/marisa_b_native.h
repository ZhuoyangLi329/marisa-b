/*
 * Public Cartesian representation used by estimator-matched shell
 * projectors.  The three rows are the closed external wavevectors.  Keeping
 * this type independent of the internal Vec3 implementation avoids coupling
 * the native API to a particular vector helper while still retaining the
 * absolute orientation required by a Cartesian CIC reconstruction window.
 */
using ClosedTriangleVectors =
    std::array<std::array<real, 3>, 3>;

