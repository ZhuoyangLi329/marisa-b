/*
 * Deterministic numerical-audit observable for the multicenter QMC measure.
 * It integrates unity over qmin<=|q|<=qmax after excising one shifted
 * spherical zero-mode region.  This is not a physical bispectrum component;
 * it exists so production builds can verify normalization, balance weights,
 * shifted-center routing, replicate errors, and exact evaluation counts
 * against an analytic volume.
 */
