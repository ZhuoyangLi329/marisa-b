constexpr double kTwoPi=6.283185307179586476925286766559005768;
constexpr double kFourPi=2.0*kTwoPi;
constexpr double kPi=0.5*kTwoPi;

using Complex=std::complex<double>;

bool finite(const Complex& value) {
    return std::isfinite(value.real()) && std::isfinite(value.imag());
}

Complex complex_gamma(Complex value) {
    // Lanczos g=7 coefficients.  Reflection is essential for the shifted
    // complex powers generated by the Laurent kernel tables.
    static constexpr std::array<double,9> coefficients={{
        0.99999999999980993,
        676.5203681218851,
        -1259.1392167224028,
        771.32342877765313,
        -176.61502916214059,
        12.507343278686905,
        -0.13857109526572012,
        9.9843695780195716e-6,
        1.5056327351493116e-7}};
    if (value.real()<0.5) {
        const Complex sine=std::sin(kPi*value);
        if (std::abs(sine)<1.0e-15) {
            throw std::domain_error("FFTLog/DR complex Gamma encountered a pole");
        }
        return kPi/(sine*complex_gamma(Complex(1.0,0.0)-value));
    }
    value-=Complex(1.0,0.0);
    Complex series(coefficients[0],0.0);
    for (std::size_t index=1;index<coefficients.size();++index) {
        series+=coefficients[index]/(value+static_cast<double>(index));
    }
    const Complex shifted=value+7.5;
    const Complex result=std::sqrt(kTwoPi)*std::pow(shifted,value+0.5)
                         *std::exp(-shifted)*series;
    if (!finite(result)) {
        throw std::overflow_error("FFTLog/DR complex Gamma is non-finite");
    }
    return result;
}

struct HypergeometricResult {
    Complex value;
    int terms=0;
};

HypergeometricResult hypergeometric_2f1(
    Complex a,Complex b,Complex c,double argument,
    double tolerance,int maximum_terms) {
    if (!(argument>=0.0 && argument<1.0)) {
        throw std::invalid_argument("FFTLog/DR 2F1 argument must be in [0,1)");
    }
    if (argument==0.0) return {Complex(1.0,0.0),1};
    Complex term(1.0,0.0);
    Complex sum(1.0,0.0);
    int stable=0;
    for (int index=0;index<maximum_terms-1;++index) {
        const Complex denominator=(c+static_cast<double>(index))
                                  *static_cast<double>(index+1);
        if (std::abs(denominator)<1.0e-15) {
            throw std::domain_error("FFTLog/DR 2F1 denominator encountered a pole");
        }
        term*=((a+static_cast<double>(index))*(b+static_cast<double>(index))
               /denominator)*argument;
        sum+=term;
        if (!finite(sum) || !finite(term)) {
            throw std::overflow_error("FFTLog/DR 2F1 series is non-finite");
        }
        if (std::abs(term)<=tolerance*std::max(1.0,std::abs(sum))) ++stable;
        else stable=0;
        if (stable>=3) return {sum,index+2};
    }
    throw std::runtime_error("FFTLog/DR 2F1 series did not converge");
}

