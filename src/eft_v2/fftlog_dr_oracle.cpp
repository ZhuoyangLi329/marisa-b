FftlogDrMasterResult fftlog_dr_master_integral(
    std::complex<double> nu1,std::complex<double> nu2,
    std::complex<double> nu3,double x,double y,
    FftlogDrMasterConfig config) {
    if (!(x>0.0 && x<=y && y<=1.0)) {
        throw std::invalid_argument(
            "FFTLog/DR master integral requires canonical 0<x<=y<=1");
    }
    if (!(config.relative_tolerance>0.0 && config.relative_tolerance<1.0
          && config.maximum_outer_terms>=8
          && config.maximum_hypergeometric_terms>=16)) {
        throw std::invalid_argument("invalid FFTLog/DR master-series configuration");
    }
    const Complex nu123=nu1+nu2+nu3;
    Complex first=complex_gamma(2.0-2.0*nu2)
                  *complex_gamma(2.0-2.0*nu3)
                  *std::sin(kPi*nu2)*std::sin(kPi*nu3)
                  /complex_gamma(5.0-2.0*nu2-2.0*nu3);
    Complex second=complex_gamma(2.0-2.0*nu1)
                   *complex_gamma(2.0*(nu123-2.0))
                   *std::sin(kPi*nu1)*std::sin(kPi*nu123)
                   /complex_gamma(-1.0+2.0*nu2+2.0*nu3);
    Complex sum_first(0.0,0.0);
    Complex sum_second(0.0,0.0);
    Complex last_delta(0.0,0.0);
    int stable=0;
    FftlogDrMasterResult result;
    const Complex x_power=std::pow(x,1.5-nu2-nu3);
    const Complex y_power=std::pow(y,1.5-nu1-nu3);
    const double hypergeometric_tolerance=0.1*config.relative_tolerance;
    for (int index=0;index<config.maximum_outer_terms;++index) {
        const double order=static_cast<double>(index);
        const HypergeometricResult hyper_first=hypergeometric_2f1(
            nu1+order,1.5-nu2+order,3.0-nu2-nu3+2.0*order,
            1.0-y,hypergeometric_tolerance,
            config.maximum_hypergeometric_terms);
        const HypergeometricResult hyper_second=hypergeometric_2f1(
            nu2+order,1.5-nu1+order,nu2+nu3+2.0*order,
            1.0-y,hypergeometric_tolerance,
            config.maximum_hypergeometric_terms);
        result.maximum_hypergeometric_terms_used=std::max({
            result.maximum_hypergeometric_terms_used,
            hyper_first.terms,hyper_second.terms});
        const Complex term_first=first*hyper_first.value;
        const Complex term_second=second*hyper_second.value;
        sum_first+=term_first;
        sum_second+=term_second;
        last_delta=x_power*term_first-y_power*term_second;
        const Complex combined=x_power*sum_first-y_power*sum_second;
        if (index>=5 && std::abs(last_delta)
                <=config.relative_tolerance*std::max(1.0,std::abs(combined))) {
            ++stable;
        } else stable=0;
        result.outer_terms=index+1;
        if (stable>=3) break;
        if (index+1==config.maximum_outer_terms) {
            throw std::runtime_error("FFTLog/DR master outer series did not converge");
        }
        const Complex first_denominator=
            (1.0+order)*(2.5-nu2-nu3+order)
            *(4.0-nu2-nu3+2.0*order)*(3.0-nu2-nu3+2.0*order);
        const Complex second_denominator=
            (1.0+order)*(nu2+nu3-0.5+order)
            *(1.0+nu2+nu3+2.0*order)*(nu2+nu3+2.0*order);
        if (std::abs(first_denominator)<1.0e-15
            || std::abs(second_denominator)<1.0e-15) {
            throw std::domain_error("FFTLog/DR master recurrence encountered a pole");
        }
        first*=x*(order+nu1)*(3.0-nu123+order)
               *(1.5-nu3+order)*(1.5-nu2+order)/first_denominator;
        second*=x*(1.5-nu1+order)*(nu123-1.5+order)
                *(order+nu2)*(order+nu3)/second_denominator;
    }
    const Complex secant=1.0/std::cos(kPi*(nu2+nu3));
    result.value=secant/(2.0*kPi*kPi)
                 *(x_power*sum_first-y_power*sum_second);
    if (!finite(result.value)) {
        throw std::overflow_error("FFTLog/DR master result is non-finite");
    }
    result.relative_tail=std::abs(secant/(2.0*kPi*kPi)*last_delta)
                         /std::max(std::abs(result.value),1.0e-300);
    return result;
}

std::complex<double> fftlog_dr_two_propagator_integral(
    std::complex<double> nu1,std::complex<double> nu2) {
    const auto inverse_gamma=[](Complex value) {
        if (std::fabs(value.imag())<1.0e-13 && value.real()<=0.0
            && std::fabs(value.real()-std::round(value.real()))<1.0e-13) {
            return Complex(0.0,0.0);
        }
        return Complex(1.0,0.0)/complex_gamma(value);
    };
    const Complex nu12=nu1+nu2;
    const Complex value=
        complex_gamma(1.5-nu1)
        *complex_gamma(1.5-nu2)
        *complex_gamma(nu12-1.5)
        *inverse_gamma(nu1)
        *inverse_gamma(nu2)
        *inverse_gamma(3.0-nu12)
        /(8.0*std::pow(kPi,1.5));
    if (!finite(value)) {
        throw std::overflow_error(
            "FFTLog/DR two-propagator master is non-finite");
    }
    return value;
}

