double integer_power(double base,int exponent) {
    if (!(base>0.0)) throw std::invalid_argument("Laurent base must be positive");
    double result=1.0;
    if (exponent>=0) {
        for (int index=0;index<exponent;++index) result*=base;
    } else {
        for (int index=0;index<-exponent;++index) result/=base;
    }
    return result;
}

double radical_inverse(unsigned int index,unsigned int base) {
    double result=0.0;
    double factor=1.0/static_cast<double>(base);
    while (index>0U) {
        result+=factor*static_cast<double>(index%base);
        index/=base;
        factor/=static_cast<double>(base);
    }
    return result;
}

Vec3 laurent_sample_loop(unsigned int sequence,double scale) {
    const double radial_fraction=radical_inverse(sequence,2U);
    const double polar_fraction=radical_inverse(sequence,3U);
    const double azimuth_fraction=radical_inverse(sequence,5U);
    const double radius=std::exp(
        std::log(0.25)+radial_fraction*std::log(4.0/0.25));
    const double z=1.0-2.0*polar_fraction;
    const double transverse=std::sqrt(std::max(0.0,1.0-z*z));
    const double phi=kTwoPi*azimuth_fraction;
    return Vec3{
        scale*radius*transverse*std::cos(phi),
        scale*radius*transverse*std::sin(phi),
        scale*radius*z};
}

std::array<double,3> laurent_variables(
    const std::array<Vec3,3>& centers,const Vec3& loop,double scale) {
    const double inverse_scale_square=1.0/(scale*scale);
    std::array<double,3> result={};
    for (int index=0;index<3;++index) {
        const Vec3 shifted{
            loop.x-centers[index].x,
            loop.y-centers[index].y,
            loop.z-centers[index].z};
        result[static_cast<std::size_t>(index)]=
            marisa_b_halo_v1::dot(shifted,shifted)*inverse_scale_square;
    }
    return result;
}

double laurent_feature(
    const std::array<double,3>& variables,const std::array<int,3>& powers) {
    return integer_power(variables[0],powers[0])
           *integer_power(variables[1],powers[1])
           *integer_power(variables[2],powers[2]);
}

double polynomial_maximum_absolute(const SparsePolynomial& value) {
    double result=0.0;
    for (const auto& term:value.terms()) result=std::max(result,std::fabs(term.second));
    return result;
}

FftlogAnalyticRegulatedDiagramResult first_order_regulator_extrapolation(
    FftlogAnalyticDiagramResult coarse,
    FftlogAnalyticDiagramResult fine,
    const FftlogRegulatorConfig& config) {
    const double ratio=config.refinement_ratio;
    FftlogAnalyticRegulatedDiagramResult result;
    result.coarse_value=coarse.value;
    result.fine_value=fine.value;
    result.extrapolated=std::move(fine);
    result.extrapolated.value=
        (1.0/(ratio-1.0))
        *(ratio*result.fine_value-result.coarse_value);
    result.extrapolated.master_integral_evaluations+=
        coarse.master_integral_evaluations;
    result.extrapolated.maximum_imaginary_to_real=std::max(
        result.extrapolated.maximum_imaginary_to_real,
        coarse.maximum_imaginary_to_real);

    result.regulator.coarse_epsilon=config.coarse_epsilon;
    result.regulator.fine_epsilon=config.coarse_epsilon/ratio;
    result.regulator.refinement_ratio=ratio;
    const SparsePolynomial coarse_to_fine=
        result.fine_value-result.coarse_value;
    const SparsePolynomial extrapolation_correction=
        result.extrapolated.value-result.fine_value;
    result.regulator.maximum_absolute_coarse_to_fine=
        polynomial_maximum_absolute(coarse_to_fine);
    result.regulator.maximum_absolute_extrapolation_correction=
        polynomial_maximum_absolute(extrapolation_correction);
    const double coarse_fine_scale=std::max({
        polynomial_maximum_absolute(result.coarse_value),
        polynomial_maximum_absolute(result.fine_value),
        1.0e-300});
    const double extrapolated_scale=std::max({
        polynomial_maximum_absolute(result.extrapolated.value),
        polynomial_maximum_absolute(result.fine_value),
        1.0e-300});
    result.regulator.maximum_relative_coarse_to_fine=
        result.regulator.maximum_absolute_coarse_to_fine/coarse_fine_scale;
    result.regulator.maximum_relative_extrapolation_correction=
        result.regulator.maximum_absolute_extrapolation_correction
        /extrapolated_scale;
    return result;
}

void merge_analytic_diagram(
    FftlogAnalyticDiagramResult& target,
    const FftlogAnalyticDiagramResult& source) {
    target.value+=source.value;
    target.reduction.basis_terms+=source.reduction.basis_terms;
    target.reduction.training_samples+=source.reduction.training_samples;
    target.reduction.validation_samples+=source.reduction.validation_samples;
    target.reduction.maximum_validation_absolute_error=std::max(
        target.reduction.maximum_validation_absolute_error,
        source.reduction.maximum_validation_absolute_error);
    target.reduction.maximum_validation_relative_error=std::max(
        target.reduction.maximum_validation_relative_error,
        source.reduction.maximum_validation_relative_error);
    target.route_reductions.insert(
        target.route_reductions.end(),
        source.route_reductions.begin(),source.route_reductions.end());
    target.fftlog_modes_used=std::max(
        target.fftlog_modes_used,source.fftlog_modes_used);
    target.master_integral_evaluations+=
        source.master_integral_evaluations;
    target.maximum_imaginary_to_real=std::max(
        target.maximum_imaginary_to_real,
        source.maximum_imaginary_to_real);
}

void validate_regulator_config(const FftlogRegulatorConfig& config) {
    if (!(config.coarse_epsilon>0.0
          && config.coarse_epsilon<1.0e-3
          && std::isfinite(config.coarse_epsilon))) {
        throw std::invalid_argument(
            "FFTLog analytic coarse regulator must be finite and in (0,1e-3)");
    }
    if (!(config.refinement_ratio>1.0
          && std::isfinite(config.refinement_ratio))) {
        throw std::invalid_argument(
            "FFTLog analytic regulator refinement ratio must be finite and >1");
    }
    const double fine=config.coarse_epsilon/config.refinement_ratio;
    if (!(fine>0.0 && fine<config.coarse_epsilon && std::isfinite(fine))) {
        throw std::invalid_argument(
            "FFTLog analytic fine regulator is not representable");
    }
}

constexpr std::size_t kB222OperatorCount=10;
