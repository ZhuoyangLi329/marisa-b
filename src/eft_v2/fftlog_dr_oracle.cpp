double signed_integer_power(double base,int exponent) {
    if (exponent<0 && base==0.0) {
        throw std::domain_error(
            "generated B411 UV expression divides by zero");
    }
    double result=1.0;
    if (exponent>=0) {
        for (int index=0;index<exponent;++index) result*=base;
    } else {
        for (int index=0;index<-exponent;++index) result/=base;
    }
    return result;
}

std::array<double,kBiasParameterCount> generated_b411_uv_coefficients(
    double k1,double k2,double k3) {
    if (!(k1>0.0 && k2>0.0 && k3>0.0
          && std::isfinite(k1) && std::isfinite(k2)
          && std::isfinite(k3))) {
        throw std::invalid_argument(
            "generated B411 UV expression requires finite positive sides");
    }
    std::array<double,kBiasParameterCount> result={};
    std::vector<double> stack;
    for (const auto& program:generated_b411::kUvPrograms) {
        stack.clear();
        stack.reserve(program.count);
        const std::size_t begin=program.offset;
        const std::size_t end=begin+program.count;
        if (end>generated_b411::kUvInstructions.size()
            || program.operator_index>=kBiasParameterCount) {
            throw std::logic_error(
                "generated B411 UV program lies outside its table");
        }
        for (std::size_t index=begin;index<end;++index) {
            const auto& instruction=
                generated_b411::kUvInstructions[index];
            using Opcode=generated_b411::UvOpcode;
            if (instruction.opcode==Opcode::Constant) {
                if (instruction.denominator==0) {
                    throw std::logic_error(
                        "generated B411 UV constant has zero denominator");
                }
                stack.push_back(
                    static_cast<double>(instruction.numerator)
                    /static_cast<double>(instruction.denominator));
                continue;
            }
            if (instruction.opcode==Opcode::K1
                || instruction.opcode==Opcode::K2
                || instruction.opcode==Opcode::K3) {
                stack.push_back(
                    instruction.opcode==Opcode::K1?k1:
                    instruction.opcode==Opcode::K2?k2:k3);
                continue;
            }
            if (instruction.opcode==Opcode::IntegerPower) {
                if (stack.empty()) {
                    throw std::logic_error(
                        "generated B411 UV power has an empty stack");
                }
                stack.back()=signed_integer_power(
                    stack.back(),instruction.exponent);
                continue;
            }
            if (stack.size()<2) {
                throw std::logic_error(
                    "generated B411 UV binary operation has a short stack");
            }
            const double right=stack.back();
            stack.pop_back();
            const double left=stack.back();
            stack.pop_back();
            if (instruction.opcode==Opcode::Add) {
                stack.push_back(left+right);
            } else if (instruction.opcode==Opcode::Multiply) {
                stack.push_back(left*right);
            } else {
                throw std::logic_error(
                    "generated B411 UV program has an unknown opcode");
            }
        }
        if (stack.size()!=1 || !std::isfinite(stack.back())) {
            throw std::runtime_error(
                "generated B411 UV program returned an invalid scalar");
        }
        result[program.operator_index]=stack.back();
    }
    return result;
}

QuadratureRule gauss_legendre(int count,double lower,double upper) {
    if (count<1 || !(upper>lower)) {
        throw std::invalid_argument("invalid FFTLog/DR radial rule");
    }
    QuadratureRule result;
    result.nodes.resize(count);
    result.weights.resize(count);
    const int half=(count+1)/2;
    const double midpoint=0.5*(lower+upper);
    const double half_width=0.5*(upper-lower);
    for (int index=0;index<half;++index) {
        double root=std::cos(
            0.5*kTwoPi*(static_cast<double>(index)+0.75)
            /(static_cast<double>(count)+0.5));
        double derivative=0.0;
        for (int iteration=0;iteration<100;++iteration) {
            double previous=1.0;
            double current=root;
            for (int order=2;order<=count;++order) {
                const double next=((2.0*order-1.0)*root*current
                                   -(order-1.0)*previous)/order;
                previous=current;
                current=next;
            }
            const double pn=count==1?root:current;
            const double pnm1=count==1?1.0:previous;
            derivative=count*(root*pn-pnm1)/(root*root-1.0);
            const double update=pn/derivative;
            root-=update;
            if (std::fabs(update)<4.0*std::numeric_limits<double>::epsilon()) break;
        }
        const double weight=2.0/((1.0-root*root)*derivative*derivative);
        result.nodes[index]=midpoint-half_width*root;
        result.nodes[count-1-index]=midpoint+half_width*root;
        result.weights[index]=half_width*weight;
        result.weights[count-1-index]=half_width*weight;
    }
    return result;
}

double normalized_linear_power_uv_moment(
    const PowerSpectrum& power,
    const FftlogUvRestorationConfig& config) {
    if (!(config.moment_kmin>0.0
          && config.moment_kmax>config.moment_kmin
          && std::isfinite(config.moment_kmin)
          && std::isfinite(config.moment_kmax)
          && config.moment_quadrature_order>=16
          && config.angular_n_mu>=2
          && config.angular_n_phi>=2)) {
        throw std::invalid_argument(
            "invalid FFTLog UV-restoration configuration");
    }
    const double ratio=std::sqrt(2.0);
    const double low_value=power(config.moment_kmin);
    const double low_inner=power(config.moment_kmin*ratio);
    const double high_inner=power(config.moment_kmax/ratio);
    const double high_value=power(config.moment_kmax);
    if (!(low_value>0.0 && low_inner>0.0
          && high_inner>0.0 && high_value>0.0
          && std::isfinite(low_value) && std::isfinite(low_inner)
          && std::isfinite(high_inner) && std::isfinite(high_value))) {
        throw std::invalid_argument(
            "UV-restoration moment sampled a non-positive power spectrum");
    }
    const double low_slope=
        std::log(low_inner/low_value)/std::log(ratio);
    const double high_slope=
        std::log(high_value/high_inner)/std::log(ratio);
    if (!(low_slope>-1.0 && high_slope<-1.0)) {
        throw std::domain_error(
            "UV-restoration integral P(q)dq has a non-convergent power-law tail");
    }
    const QuadratureRule logarithmic=gauss_legendre(
        config.moment_quadrature_order,
        std::log(config.moment_kmin),
        std::log(config.moment_kmax));
    long double middle=0.0L;
    for (std::size_t index=0;index<logarithmic.nodes.size();++index) {
        const double q=std::exp(logarithmic.nodes[index]);
        const double value=power(q);
        if (!(value>0.0 && std::isfinite(value))) {
            throw std::invalid_argument(
                "UV-restoration moment encountered invalid power");
        }
        middle+=static_cast<long double>(logarithmic.weights[index])
                *q*value;
    }
    const long double low_tail=
        static_cast<long double>(low_value)*config.moment_kmin
        /(low_slope+1.0);
    const long double high_tail=
        static_cast<long double>(high_value)*config.moment_kmax
        /(-high_slope-1.0);
    const long double total=low_tail+middle+high_tail;
    const double normalized=static_cast<double>(
        total/(2.0L*kPi*kPi));
    if (!(normalized>0.0 && std::isfinite(normalized))) {
        throw std::runtime_error(
            "UV-restoration moment is non-positive or non-finite");
    }
    return normalized;
}

Vec3 scale(const Vec3& value,double factor) {
    return Vec3{factor*value.x,factor*value.y,factor*value.z};
}

std::vector<Vec3> antipodal_fibonacci_sphere(int requested_count) {
    int count=std::max(32,requested_count);
    if (count%2!=0) ++count;
    const int half=count/2;
    const double golden_angle=0.5*kTwoPi*(3.0-std::sqrt(5.0));
    std::vector<Vec3> directions;
    directions.reserve(count);
    for (int index=0;index<half;++index) {
        const double z=(index+0.5)/static_cast<double>(half);
        const double transverse=std::sqrt(std::max(0.0,1.0-z*z));
        const double phi=golden_angle*index;
        const Vec3 value{transverse*std::cos(phi),transverse*std::sin(phi),z};
        directions.push_back(value);
        directions.push_back(scale(value,-1.0));
    }
    return directions;
}

void add_unique_break(std::vector<double>& breaks,double value) {
    if (value>breaks.front() && value<breaks.back()) breaks.push_back(value);
}

std::vector<double> bare_radial_breaks(
    const std::array<Vec3,3>& external,double qmin,double qmax) {
    std::vector<double> breaks={qmin,qmax};
    for (const Vec3& value:external) {
        add_unique_break(breaks,marisa_b_halo_v1::norm(value));
    }
    std::sort(breaks.begin(),breaks.end());
    breaks.erase(std::unique(breaks.begin(),breaks.end(),[](double left,double right) {
        return std::fabs(left-right)<=1.0e-13*std::max({left,right,1.0});
    }),breaks.end());
    return breaks;
}

void accumulate(
    DiagramTemplates& output,const DiagramIntegrands& bare,
    const UvSubtractionComponents* subtraction,double weight) {
    output.B222+=weight*bare.B222;
    output.B321I+=weight*bare.B321I;
    output.B321II_bare+=weight*bare.B321II;
    output.B411_bare+=weight*bare.B411;
    if (subtraction) {
        output.B321II_uv_subtraction+=weight*subtraction->B321II;
        output.B411_uv_subtraction+=weight*subtraction->B411;
        output.B321II+=weight*(bare.B321II-subtraction->B321II);
        output.B411+=weight*(bare.B411-subtraction->B411);
    } else {
        output.B321II+=weight*bare.B321II;
        output.B411+=weight*bare.B411;
    }
}

DiagramTemplates evaluate_fibonacci_dr(
    const PowerSpectrum& power,const std::array<Vec3,3>& triangle,
    const FieldKernelProvider& provider,const DirectIntegrationConfig& config) {
    if (!(config.qmin>0.0 && config.qmax>config.qmin)) {
        throw std::invalid_argument("FFTLog/DR oracle requires 0<qmin<qmax");
    }
    DiagramAssembler assembler(power,triangle,provider);
    IrSafeIntegrands mapped(assembler,config.qmax);
    UvSubtraction uv(assembler,config.uv);
    DiagramTemplates output;
    output.external=assembler.external();
    output.tree=assembler.tree();
    output.ir_safe=config.ir_safe;
    const std::vector<Vec3> directions=antipodal_fibonacci_sphere(
        2*config.n_mu*config.n_phi);
    const double angular_weight=kFourPi/directions.size();
    const double measure=1.0/(kTwoPi*kTwoPi*kTwoPi);
    const std::vector<double> bare_breaks=bare_radial_breaks(
        output.external,config.qmin,config.qmax);
    for (const Vec3& direction:directions) {
        const std::vector<double> boundaries=config.ir_safe
            ?mapped.radial_boundaries(direction,config.qmin):bare_breaks;
        for (std::size_t segment=0;segment+1<boundaries.size();++segment) {
            const QuadratureRule radial=gauss_legendre(
                config.n_radial,std::log(boundaries[segment]),
                std::log(boundaries[segment+1]));
            for (std::size_t index=0;index<radial.nodes.size();++index) {
                const double radius=std::exp(radial.nodes[index]);
                const Vec3 loop=scale(direction,radius);
                const DiagramIntegrands bare=config.ir_safe
                    ?mapped.all(loop):assembler.integrands(loop);
                UvSubtractionComponents subtraction;
                const UvSubtractionComponents* subtraction_pointer=nullptr;
                if (config.uv_subtract && radius<=config.qmax) {
                    subtraction=uv.integrands(loop);
                    subtraction_pointer=&subtraction;
                }
                const double weight=radial.weights[index]*radius*radius*radius
                                    *angular_weight*measure;
                accumulate(output,bare,subtraction_pointer,weight);
                ++output.integration_nodes;
            }
        }
    }
    output.uv_subtraction_total=
        output.B321II_uv_subtraction+output.B411_uv_subtraction;
    output.one_loop=output.B222+output.B321I+output.B321II+output.B411;
    output.total=output.tree+output.one_loop;
    return output;
}

