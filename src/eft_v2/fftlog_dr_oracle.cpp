FftlogLaurentReduction fftlog_dr_reduce_b222_kernel(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,FftlogLaurentConfig config) {
    const UnitPower unit_power;
    const DiagramAssembler assembler(unit_power,closed_triangle,provider);
    const auto& external=assembler.external();
    const double scale=marisa_b_halo_v1::norm(external[2]);
    const std::array<Vec3,3> centers={{
        Vec3{},external[0],marisa_b_halo_v1::negate(external[1])}};
    return reduce_laurent_kernel(
        {centers},scale,
        [&assembler](const Vec3& loop) {
            return assembler.integrand(Diagram::B222,loop);
        },config);
}

FftlogLaurentReduction fftlog_dr_reduce_b321i_route_kernel(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    int external_power_index,int shifted_power_index,
    FftlogLaurentConfig config) {
    if (external_power_index<0 || external_power_index>=3
        || shifted_power_index<0 || shifted_power_index>=3
        || external_power_index==shifted_power_index) {
        throw std::invalid_argument("invalid FFTLog B321I route indices");
    }
    const UnitPower unit_power;
    const DiagramAssembler assembler(unit_power,closed_triangle,provider);
    const auto& external=assembler.external();
    const double scale=marisa_b_halo_v1::norm(external[2]);
    const auto charts=b321i_route_charts(
        external,external_power_index,shifted_power_index);
    return reduce_laurent_kernel(
        charts,scale,
        [&assembler,external_power_index,shifted_power_index](
            const Vec3& loop) {
            return assembler.b321i_route(
                external_power_index,shifted_power_index,loop);
        },config,true);
}

FftlogLaurentReduction fftlog_dr_reduce_b321ii_route_kernel(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    int left_external_index,int right_external_index,
    int tadpole_external_index,FftlogLaurentConfig config) {
    if (left_external_index<0 || left_external_index>=3
        || right_external_index<0 || right_external_index>=3
        || left_external_index>=right_external_index
        || (tadpole_external_index!=left_external_index
            && tadpole_external_index!=right_external_index)) {
        throw std::invalid_argument("invalid FFTLog B321II route indices");
    }
    const UnitPower unit_power;
    const DiagramAssembler assembler(unit_power,closed_triangle,provider);
    const auto& external=assembler.external();
    const Vec3 tadpole_external=
        external[static_cast<std::size_t>(tadpole_external_index)];
    const double scale=2.0*marisa_b_halo_v1::norm(tadpole_external);
    const std::array<Vec3,3> centers={{
        Vec3{},tadpole_external,
        marisa_b_halo_v1::negate(tadpole_external)}};
    return reduce_laurent_kernel(
        {centers},scale,
        [&assembler,left_external_index,right_external_index,
         tadpole_external_index](const Vec3& loop) {
            return assembler.b321ii_route(
                left_external_index,right_external_index,
                tadpole_external_index,loop);
        },config);
}

FftlogPowerSpectrum::FftlogPowerSpectrum(
    const PowerSpectrum& source,FftlogConfig config)
    : source_(source),config_(config) {
    if (!(config_.kmin>0.0 && config_.kmax>config_.kmin)) {
        throw std::invalid_argument("FFTLog requires 0<kmin<kmax");
    }
    if (config_.frequency_count<8 || config_.frequency_count%2!=0) {
        throw std::invalid_argument("FFTLog frequency count must be even and at least eight");
    }
    if (config_.reconstruction_grid_size<config_.frequency_count) {
        throw std::invalid_argument("FFTLog reconstruction grid is too short");
    }
    log_kmin_=std::log(config_.kmin);
    log_span_=std::log(config_.kmax/config_.kmin);
    const int count=config_.frequency_count;
    const double sample_step=config_.endpoint_inclusive_sampling
        ?log_span_/static_cast<double>(count-1)
        :log_span_/static_cast<double>(count);
    log_period_=sample_step*count;
    if (std::isfinite(config_.bias_nu)) actual_bias_nu_=config_.bias_nu;
    else {
        const double low=source_(config_.kmin);
        const double high=source_(config_.kmax);
        if (!(low>0.0 && high>0.0)) throw std::invalid_argument("FFTLog source power must be positive");
        actual_bias_nu_=std::log(high/low)/log_span_;
    }
    std::vector<double> biased(count);
    for (int sample=0;sample<count;++sample) {
        const double x=sample_step*sample;
        const double k=std::exp(log_kmin_+x);
        const double value=source_(k)*std::exp(-actual_bias_nu_*(log_kmin_+x));
        if (!(value>0.0 && std::isfinite(value))) {
            throw std::invalid_argument("FFTLog sampled non-positive or non-finite power");
        }
        biased[sample]=value;
    }
    coefficients_.resize(count);
    for (int mode=0;mode<count;++mode) {
        std::complex<long double> coefficient(0.0L,0.0L);
        for (int sample=0;sample<count;++sample) {
            const long double phase=-kTwoPi*mode*sample/static_cast<long double>(count);
            coefficient+=static_cast<long double>(biased[sample])
                         *std::complex<long double>(std::cos(phase),std::sin(phase));
        }
        coefficient/=static_cast<long double>(count);
        coefficients_[mode]={static_cast<double>(coefficient.real()),static_cast<double>(coefficient.imag())};
    }

    if (!config_.reconstruct_interpolated_power) return;
    dense_log_power_.resize(config_.reconstruction_grid_size);
    for (int index=0;index<config_.reconstruction_grid_size;++index) {
        const double fraction=index/static_cast<double>(config_.reconstruction_grid_size-1);
        const double x=fraction*log_span_;
        std::complex<long double> biased_value(0.0L,0.0L);
        for (int mode=0;mode<count;++mode) {
            const int signed_mode=mode<=count/2?mode:mode-count;
            const long double phase=kTwoPi*signed_mode*x/log_period_;
            biased_value+=std::complex<long double>(
                coefficients_[mode].real(),coefficients_[mode].imag())
                *std::complex<long double>(std::cos(phase),std::sin(phase));
        }
        const double power=static_cast<double>(biased_value.real())
                           *std::exp(actual_bias_nu_*(log_kmin_+x));
        if (!(power>0.0 && std::isfinite(power))) {
            throw std::runtime_error("FFTLog reconstruction produced non-positive power");
        }
        dense_log_power_[index]=std::log(power);
    }
}

real FftlogPowerSpectrum::Evaluate(real k) const {
    if (!(k>0.0)) return 0.0;
    if (dense_log_power_.empty()) {
        throw std::logic_error(
            "FFTLog interpolated power was disabled for this analytic-only "
            "mode expansion");
    }
    const double log_k=std::log(k);
    double position=(log_k-log_kmin_)/log_span_*(dense_log_power_.size()-1);
    if (position<=0.0) {
        const double slope=(dense_log_power_[1]-dense_log_power_[0])
                           *(dense_log_power_.size()-1)/log_span_;
        return std::exp(dense_log_power_[0]+slope*(log_k-log_kmin_));
    }
    if (position>=dense_log_power_.size()-1) {
        const std::size_t last=dense_log_power_.size()-1;
        const double slope=(dense_log_power_[last]-dense_log_power_[last-1])
                           *(dense_log_power_.size()-1)/log_span_;
        return std::exp(dense_log_power_[last]
                        +slope*(log_k-(log_kmin_+log_span_)));
    }
    const std::size_t left=static_cast<std::size_t>(std::floor(position));
    const double fraction=position-left;
    return std::exp((1.0-fraction)*dense_log_power_[left]
                    +fraction*dense_log_power_[left+1]);
}

