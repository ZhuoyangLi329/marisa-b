Complex master_with_exact_scaleless_reduction(
    const std::array<Complex,3>& unregulated_nu,
    double analytic_regulator_epsilon,
    double x,double y,
    const FftlogDrMasterConfig& master) {
    std::array<int,3> zero_indices={{-1,-1,-1}};
    int zero_count=0;
    for (int index=0;index<3;++index) {
        if (std::abs(unregulated_nu[static_cast<std::size_t>(index)])
                <1.0e-14) {
            zero_indices[static_cast<std::size_t>(zero_count++)]=index;
        }
    }
    // With two or three absent propagators, the remaining scale-free
    // integral vanishes in dimensional regularization.
    if (zero_count>=2) return Complex(0.0,0.0);
    if (zero_count==1) {
        const int absent=zero_indices[0];
        if (absent==0) {
            return std::pow(
                x,1.5-unregulated_nu[1]-unregulated_nu[2])
                *fftlog_dr_two_propagator_integral(
                    unregulated_nu[1],unregulated_nu[2]);
        }
        if (absent==1) {
            return std::pow(
                y,1.5-unregulated_nu[0]-unregulated_nu[2])
                *fftlog_dr_two_propagator_integral(
                    unregulated_nu[0],unregulated_nu[2]);
        }
        return fftlog_dr_two_propagator_integral(
            unregulated_nu[0],unregulated_nu[1]);
    }
    std::array<Complex,3> regulated_nu=unregulated_nu;
    for (auto& value:regulated_nu) value+=analytic_regulator_epsilon;
    return fftlog_dr_master_integral(
        regulated_nu[0],regulated_nu[1],regulated_nu[2],
        x,y,master).value;
}

