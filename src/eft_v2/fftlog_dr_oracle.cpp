using B411CoefficientMatrix=
    std::array<std::array<double,112>,kBiasParameterCount>;

B411CoefficientMatrix generated_b411_coefficients(double x,double y) {
    if (!(x>0.0 && y>0.0)) {
        throw std::invalid_argument(
            "generated B411 coefficients require positive shape ratios");
    }
    B411CoefficientMatrix result={};
    for (const auto& term:generated_b411::kCoefficients) {
        const double coefficient=
            static_cast<double>(term.numerator)
            /static_cast<double>(term.denominator)
            *integer_power(x,term.x_power)
            *integer_power(y,term.y_power);
        result[term.operator_index][term.frequency_index]+=coefficient;
    }
    return result;
}

