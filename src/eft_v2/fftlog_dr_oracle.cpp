SparsePolynomial fftlog_b321ii_exact_uv_restoration(
    const PowerSpectrum& source,
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    double normalized_linear_power_moment) {
    if (!(normalized_linear_power_moment>=0.0
          && std::isfinite(normalized_linear_power_moment))) {
        throw std::invalid_argument(
            "B321II UV restoration requires a finite non-negative moment");
    }
    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<Vec3,3> external={{
        canonical.k1,canonical.k2,canonical.k3}};
    std::array<double,3> power={};
    for (std::size_t index=0;index<external.size();++index) {
        power[index]=source(marisa_b_halo_v1::norm(external[index]));
    }
    const SparsePolynomial alpha=p13_uv_coefficient(provider);
    SparsePolynomial result;
    for (int left=0;left<3;++left) {
        for (int right=left+1;right<3;++right) {
            const SparsePolynomial K2=provider.deterministic(
                {external[static_cast<std::size_t>(left)],
                 external[static_cast<std::size_t>(right)]});
            for (const int tadpole:{left,right}) {
                const int linear=tadpole==left?right:left;
                const double ktad=
                    marisa_b_halo_v1::norm(
                        external[static_cast<std::size_t>(tadpole)]);
                const SparsePolynomial K1=provider.deterministic(
                    {external[static_cast<std::size_t>(linear)]});
                result+=normalized_linear_power_moment
                    *power[static_cast<std::size_t>(left)]
                    *power[static_cast<std::size_t>(right)]
                    *ktad*ktad*K2*K1*alpha;
            }
        }
    }
    return result;
}

SparsePolynomial fftlog_b411_exact_uv_restoration(
    const PowerSpectrum& source,
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    double normalized_linear_power_moment) {
    if (!(normalized_linear_power_moment>=0.0
          && std::isfinite(normalized_linear_power_moment))) {
        throw std::invalid_argument(
            "B411 UV restoration requires a finite non-negative moment");
    }
    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<double,3> sides={{
        canonical.sides.k1,canonical.sides.k2,canonical.sides.k3}};
    // These are the upstream 123, 231 and 132 routes, respectively.  The
    // first two entries are the external linear legs and the third closes
    // the triangle.
    static constexpr std::array<std::array<int,3>,3> routes={{
        {{2,1,0}},{{1,0,2}},{{2,0,1}}}};
    const auto operator_polynomials=b411_operator_polynomials(provider);
    SparsePolynomial result;
    for (const auto& route:routes) {
        const std::size_t first=static_cast<std::size_t>(route[0]);
        const std::size_t second=static_cast<std::size_t>(route[1]);
        const std::size_t third=static_cast<std::size_t>(route[2]);
        const auto coefficients=generated_b411_uv_coefficients(
            sides[first],sides[second],sides[third]);
        const double external_factor=
            source(sides[first])*source(sides[second])
            *normalized_linear_power_moment;
        for (std::size_t operator_index=0;
             operator_index<kBiasParameterCount;
             ++operator_index) {
            result+=external_factor*coefficients[operator_index]
                *operator_polynomials[operator_index];
        }
    }
    return result;
}

