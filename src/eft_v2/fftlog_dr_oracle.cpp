std::vector<FftlogMode> FftlogPowerSpectrum::modes() const {
    std::vector<FftlogMode> result;
    result.reserve(coefficients_.size()+1);
    const int count=static_cast<int>(coefficients_.size());
    const double pivot_k=std::exp(log_kmin_);
    const double pivot_amplitude=std::pow(pivot_k,actual_bias_nu_);
    result.push_back(FftlogMode{
        pivot_amplitude*Complex(coefficients_[0].real(),0.0),
        Complex(actual_bias_nu_,0.0),pivot_k});
    for (int mode=1;mode<count/2;++mode) {
        const double eta=kTwoPi*mode/log_period_;
        // Enforce the exact conjugacy implied by a real input.  The two DFT
        // coefficients were accumulated independently and differ at their
        // final rounding bit, which would otherwise leave a spurious public
        // mode-sum imaginary part.
        const Complex paired=0.5*(
            coefficients_[static_cast<std::size_t>(mode)]
            +std::conj(coefficients_[static_cast<std::size_t>(count-mode)]));
        const Complex positive=pivot_amplitude*paired;
        result.push_back(FftlogMode{
            positive,Complex(actual_bias_nu_,eta),pivot_k});
        result.push_back(FftlogMode{
            std::conj(positive),Complex(actual_bias_nu_,-eta),pivot_k});
    }
    // A real, even-length DFT has one Nyquist coefficient shared by +N/2
    // and -N/2.  Splitting it makes the mode sum real off the sample grid.
    const double nyquist_eta=kTwoPi*(count/2)/log_period_;
    const Complex nyquist(0.5*coefficients_[count/2].real(),0.0);
    const Complex positive_nyquist=pivot_amplitude*nyquist;
    result.push_back(FftlogMode{
        positive_nyquist,Complex(actual_bias_nu_,nyquist_eta),pivot_k});
    result.push_back(FftlogMode{
        std::conj(positive_nyquist),Complex(actual_bias_nu_,-nyquist_eta),pivot_k});
    return result;
}

