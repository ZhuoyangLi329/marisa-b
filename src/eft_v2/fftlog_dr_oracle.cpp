FftlogAnalyticDiagramResult FftlogDrOracle::evaluate_b222_analytic(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    FftlogLaurentConfig laurent,
    FftlogDrMasterConfig master,
    double mode_coefficient_relative_tolerance) const {
    if (!(mode_coefficient_relative_tolerance>=0.0
          && mode_coefficient_relative_tolerance<1.0)) {
        throw std::invalid_argument(
            "FFTLog analytic B222 mode tolerance must be in [0,1)");
    }

    FftlogAnalyticDiagramResult result;
    result.reduction=fftlog_dr_reduce_b222_kernel(
        closed_triangle,provider,laurent);

    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<Vec3,3> external={{
        canonical.k1,canonical.k2,canonical.k3}};
    const double short_scale=marisa_b_halo_v1::norm(external[0]);
    const double middle_scale=marisa_b_halo_v1::norm(external[1]);
    const double long_scale=marisa_b_halo_v1::norm(external[2]);
    if (!(short_scale>0.0 && middle_scale>=short_scale
          && long_scale>=middle_scale)) {
        throw std::invalid_argument(
            "FFTLog analytic B222 requires a non-degenerate canonical triangle");
    }
    const double x=(short_scale/long_scale)*(short_scale/long_scale);
    const double y=(middle_scale/long_scale)*(middle_scale/long_scale);

    const std::vector<FftlogMode> all_modes=power_.modes();
    double maximum_mode_coefficient=0.0;
    for (const auto& mode:all_modes) {
        maximum_mode_coefficient=std::max(
            maximum_mode_coefficient,std::abs(mode.coefficient));
    }
    if (!(maximum_mode_coefficient>0.0
          && std::isfinite(maximum_mode_coefficient))) {
        throw std::runtime_error(
            "FFTLog analytic B222 has no finite nonzero power-spectrum mode");
    }

    struct ScaledMode {
        Complex coefficient;
        Complex exponent;
    };
    std::vector<ScaledMode> modes;
    modes.reserve(all_modes.size());
    const double threshold=
        mode_coefficient_relative_tolerance*maximum_mode_coefficient;
    for (const auto& mode:all_modes) {
        if (std::abs(mode.coefficient)<=threshold) continue;
        const Complex scaled=mode.coefficient*std::exp(
            mode.exponent*std::log(long_scale/mode.pivot_k));
        if (!finite(scaled)) {
            throw std::overflow_error(
                "FFTLog analytic B222 scaled mode is non-finite");
        }
        modes.push_back(ScaledMode{scaled,mode.exponent});
    }
    if (modes.empty()) {
        throw std::runtime_error(
            "FFTLog analytic B222 mode pruning removed every mode");
    }
    result.fftlog_modes_used=static_cast<int>(modes.size());

    // Each Laurent coefficient is independent.  Parallelize only this outer
    // level: every complex mode sum retains a fixed serial order, and sparse
    // polynomials are combined afterwards in their original term order.
    // This gives deterministic output while making the cubic B222 mode
    // contraction usable at production frequency counts.
    std::vector<Complex> term_scalars(result.reduction.terms.size());
    std::vector<std::size_t> term_master_counts(
        result.reduction.terms.size(),0);
    std::atomic<bool> failed(false);
    std::exception_ptr parallel_error;
    std::mutex parallel_error_mutex;
#pragma omp parallel for schedule(dynamic)
    for (std::ptrdiff_t term_index=0;
         term_index<static_cast<std::ptrdiff_t>(
             result.reduction.terms.size());
         ++term_index) {
        if (failed.load(std::memory_order_relaxed)) continue;
        try {
            const auto& term=result.reduction.terms[
                static_cast<std::size_t>(term_index)];
            Complex scalar(0.0,0.0);
            // Laurent variables are ordered as
            //   D0=q^2, D1=|k_short-q|^2, D2=|k_middle+q|^2.
            // With q'=k_middle+q, the Simonovic master denominators are
            // (q'^2, |k_long-q'|^2, |k_middle+q'|^2)=(D2,D1,D0).
            for (const auto& mode_d0:modes) {
                for (const auto& mode_d1:modes) {
                    for (const auto& mode_d2:modes) {
                        const Complex nu1=
                            -static_cast<double>(term.powers[2])
                            -0.5*mode_d2.exponent;
                        const Complex nu2=
                            -static_cast<double>(term.powers[1])
                            -0.5*mode_d1.exponent;
                        const Complex nu3=
                            -static_cast<double>(term.powers[0])
                            -0.5*mode_d0.exponent;
                        const FftlogDrMasterResult integral=
                            fftlog_dr_master_integral(
                                nu1,nu2,nu3,x,y,master);
                        scalar+=mode_d0.coefficient
                                *mode_d1.coefficient
                                *mode_d2.coefficient
                                *integral.value;
                        ++term_master_counts[
                            static_cast<std::size_t>(term_index)];
                    }
                }
            }
            term_scalars[static_cast<std::size_t>(term_index)]=
                scalar*long_scale*long_scale*long_scale;
        } catch (...) {
            std::lock_guard<std::mutex> lock(parallel_error_mutex);
            if (!parallel_error) parallel_error=std::current_exception();
            failed.store(true,std::memory_order_relaxed);
        }
    }
    if (parallel_error) std::rethrow_exception(parallel_error);

    SparsePolynomial imaginary;
    for (std::size_t term_index=0;
         term_index<result.reduction.terms.size();++term_index) {
        const auto& term=result.reduction.terms[term_index];
        const Complex scalar=term_scalars[term_index];
        result.value+=scalar.real()*term.coefficient;
        imaginary+=scalar.imag()*term.coefficient;
        result.master_integral_evaluations+=
            term_master_counts[term_index];
    }

    const double real_scale=polynomial_maximum_absolute(result.value);
    const double imaginary_scale=polynomial_maximum_absolute(imaginary);
    result.maximum_imaginary_to_real=
        imaginary_scale/std::max(real_scale,1.0e-300);
    return result;
}

FftlogAnalyticDiagramResult
FftlogDrOracle::evaluate_b222_public_table_analytic(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    FftlogDrMasterConfig master,
    double mode_coefficient_relative_tolerance,
    std::uint64_t operator_mask) const {
    if (!(mode_coefficient_relative_tolerance>=0.0
          && mode_coefficient_relative_tolerance<1.0)) {
        throw std::invalid_argument(
            "public-table B222 mode tolerance must be in [0,1)");
    }
    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<Vec3,3> external={{
        canonical.k1,canonical.k2,canonical.k3}};
    const double short_scale=marisa_b_halo_v1::norm(external[0]);
    const double middle_scale=marisa_b_halo_v1::norm(external[1]);
    const double long_scale=marisa_b_halo_v1::norm(external[2]);
    if (!(short_scale>0.0 && middle_scale>=short_scale
          && long_scale>=middle_scale)) {
        throw std::invalid_argument(
            "public-table B222 requires a non-degenerate canonical triangle");
    }
    const double x=(short_scale/long_scale)*(short_scale/long_scale);
    const double y=(middle_scale/long_scale)*(middle_scale/long_scale);

    const std::vector<FftlogMode> all_modes=power_.modes();
    double maximum_mode_coefficient=0.0;
    for (const auto& mode:all_modes) {
        maximum_mode_coefficient=std::max(
            maximum_mode_coefficient,std::abs(mode.coefficient));
    }
    if (!(maximum_mode_coefficient>0.0
          && std::isfinite(maximum_mode_coefficient))) {
        throw std::runtime_error(
            "public-table B222 has no finite nonzero power-spectrum mode");
    }
    const double threshold=
        mode_coefficient_relative_tolerance*maximum_mode_coefficient;
    struct ScaledMode {
        Complex coefficient;
        Complex exponent;
    };
    std::vector<ScaledMode> modes;
    modes.reserve(all_modes.size());
    for (const auto& mode:all_modes) {
        if (std::abs(mode.coefficient)<=threshold) continue;
        const Complex coefficient=mode.coefficient*std::exp(
            mode.exponent*std::log(long_scale/mode.pivot_k));
        if (!finite(coefficient)) {
            throw std::overflow_error(
                "public-table B222 scaled mode is non-finite");
        }
        modes.push_back(ScaledMode{coefficient,mode.exponent});
    }
    if (modes.empty()) {
        throw std::runtime_error(
            "public-table B222 mode pruning removed every mode");
    }

    const auto coefficient_matrix=
        generated_public_loop_coefficients<
            kB222OperatorCount,
            generated_public_loops::kB222Frequencies.size()>(
                x,y,generated_public_loops::kB222Coefficients);
    std::array<bool,
        generated_public_loops::kB222Frequencies.size()>
        active_frequencies={};
    for (std::size_t operator_index=0;
         operator_index<kB222OperatorCount;++operator_index) {
        if ((operator_mask&(std::uint64_t{1}<<operator_index))==0) continue;
        for (std::size_t frequency_index=0;
             frequency_index<
                generated_public_loops::kB222Frequencies.size();
             ++frequency_index) {
            active_frequencies[frequency_index]=
                active_frequencies[frequency_index]
                || coefficient_matrix[operator_index][frequency_index]!=0.0;
        }
    }
    if (std::none_of(
            active_frequencies.begin(),active_frequencies.end(),
            [](bool value) { return value; })) {
        throw std::invalid_argument(
            "public-table B222 operator mask selects no active operator");
    }
    const auto operator_polynomials=b222_operator_polynomials(provider);
    std::array<Complex,
        generated_public_loops::kB222Frequencies.size()> frequency_values={};
    std::array<std::size_t,
        generated_public_loops::kB222Frequencies.size()> master_counts={};
    std::atomic<bool> failed(false);
    std::exception_ptr parallel_error;
    std::mutex parallel_error_mutex;
#pragma omp parallel for schedule(dynamic)
    for (std::ptrdiff_t frequency_index=0;
         frequency_index<static_cast<std::ptrdiff_t>(
             generated_public_loops::kB222Frequencies.size());
         ++frequency_index) {
        if (!active_frequencies[
                static_cast<std::size_t>(frequency_index)]) {
            continue;
        }
        if (failed.load(std::memory_order_relaxed)) continue;
        try {
            const auto& frequency=
                generated_public_loops::kB222Frequencies[
                    static_cast<std::size_t>(frequency_index)];
            Complex scalar(0.0,0.0);
            std::size_t count=0;
            for (const auto& first:modes) {
                for (const auto& second:modes) {
                    for (const auto& third:modes) {
                        const std::array<Complex,3> exponents={{
                            first.exponent,second.exponent,third.exponent}};
                        std::array<Complex,3> nu;
                        for (std::size_t denominator=0;
                             denominator<3;++denominator) {
                            const int slot=frequency.fftlog_slot[denominator];
                            if (slot<0 || slot>=3) {
                                throw std::logic_error(
                                    "public B222 frequency has invalid slot");
                            }
                            nu[denominator]=
                                static_cast<double>(
                                    frequency.shift[denominator])
                                -0.5*exponents[
                                    static_cast<std::size_t>(slot)];
                        }
                        scalar+=first.coefficient*second.coefficient
                            *third.coefficient
                            *fftlog_dr_master_integral(
                                nu[0],nu[1],nu[2],x,y,master).value;
                        ++count;
                    }
                }
            }
            frequency_values[
                static_cast<std::size_t>(frequency_index)]=scalar;
            master_counts[
                static_cast<std::size_t>(frequency_index)]=count;
        } catch (...) {
            std::lock_guard<std::mutex> lock(parallel_error_mutex);
            if (!parallel_error) parallel_error=std::current_exception();
            failed.store(true,std::memory_order_relaxed);
        }
    }
    if (parallel_error) std::rethrow_exception(parallel_error);

    FftlogAnalyticDiagramResult result;
    result.fftlog_modes_used=static_cast<int>(modes.size());
    result.reduction.basis_terms=
        static_cast<int>(std::count(
            active_frequencies.begin(),active_frequencies.end(),true));
    result.reduction.maximum_validation_absolute_error=0.0;
    result.reduction.maximum_validation_relative_error=0.0;
    SparsePolynomial imaginary;
    const double scale_cubed=
        long_scale*long_scale*long_scale;
    for (std::size_t operator_index=0;
         operator_index<kB222OperatorCount;++operator_index) {
        if ((operator_mask&(std::uint64_t{1}<<operator_index))==0) continue;
        Complex value(0.0,0.0);
        for (std::size_t frequency_index=0;
             frequency_index<
                generated_public_loops::kB222Frequencies.size();
             ++frequency_index) {
            value+=coefficient_matrix[operator_index][frequency_index]
                *frequency_values[frequency_index];
        }
        value*=scale_cubed;
        result.value+=value.real()*operator_polynomials[operator_index];
        imaginary+=value.imag()*operator_polynomials[operator_index];
    }
    for (const std::size_t count:master_counts) {
        result.master_integral_evaluations+=count;
    }
    const double real_scale=polynomial_maximum_absolute(result.value);
    const double imaginary_scale=polynomial_maximum_absolute(imaginary);
    result.maximum_imaginary_to_real=
        imaginary_scale/std::max(real_scale,1.0e-300);
    return result;
}

FftlogAnalyticDiagramResult FftlogDrOracle::evaluate_b321i_analytic(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    FftlogLaurentConfig laurent,
    FftlogDrMasterConfig master,
    double mode_coefficient_relative_tolerance,
    double analytic_regulator_epsilon) const {
    if (!(mode_coefficient_relative_tolerance>=0.0
          && mode_coefficient_relative_tolerance<1.0)) {
        throw std::invalid_argument(
            "FFTLog analytic B321I mode tolerance must be in [0,1)");
    }
    if (!(analytic_regulator_epsilon>0.0
          && analytic_regulator_epsilon<1.0e-3)) {
        throw std::invalid_argument(
            "FFTLog analytic B321I regulator must be in (0,1e-3)");
    }

    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<Vec3,3> external={{
        canonical.k1,canonical.k2,canonical.k3}};
    const double reduction_scale=marisa_b_halo_v1::norm(external[2]);
    if (!(reduction_scale>0.0)) {
        throw std::invalid_argument(
            "FFTLog analytic B321I has an invalid triangle scale");
    }

    const std::vector<FftlogMode> all_modes=power_.modes();
    double maximum_mode_coefficient=0.0;
    for (const auto& mode:all_modes) {
        maximum_mode_coefficient=std::max(
            maximum_mode_coefficient,std::abs(mode.coefficient));
    }
    if (!(maximum_mode_coefficient>0.0
          && std::isfinite(maximum_mode_coefficient))) {
        throw std::runtime_error(
            "FFTLog analytic B321I has no finite nonzero power-spectrum mode");
    }
    const double threshold=
        mode_coefficient_relative_tolerance*maximum_mode_coefficient;
    std::vector<FftlogMode> modes;
    for (const auto& mode:all_modes) {
        if (std::abs(mode.coefficient)>threshold) modes.push_back(mode);
    }
    if (modes.empty()) {
        throw std::runtime_error(
            "FFTLog analytic B321I mode pruning removed every mode");
    }

    struct ScaledMode {
        Complex coefficient;
        Complex exponent;
    };
    const auto scaled_modes=[&modes](double scale_value) {
        std::vector<ScaledMode> result;
        result.reserve(modes.size());
        for (const auto& mode:modes) {
            const Complex coefficient=mode.coefficient*std::exp(
                mode.exponent*std::log(scale_value/mode.pivot_k));
            if (!finite(coefficient)) {
                throw std::overflow_error(
                    "FFTLog analytic B321I scaled mode is non-finite");
            }
            result.push_back(ScaledMode{coefficient,mode.exponent});
        }
        return result;
    };
    const std::vector<ScaledMode> modes_at_reduction_scale=
        scaled_modes(reduction_scale);

    FftlogAnalyticDiagramResult result;
    result.fftlog_modes_used=static_cast<int>(modes.size());
    result.route_reductions.reserve(6);
    SparsePolynomial imaginary;
    for (int shifted=0;shifted<3;++shifted) {
        const double shifted_scale=marisa_b_halo_v1::norm(
            external[static_cast<std::size_t>(shifted)]);
        const std::vector<ScaledMode> modes_at_shifted_scale=
            scaled_modes(shifted_scale);
        for (int external_power=0;external_power<3;++external_power) {
            if (external_power==shifted) continue;
            FftlogLaurentReduction reduction=
                fftlog_dr_reduce_b321i_route_kernel(
                    closed_triangle,provider,
                    external_power,shifted,laurent);
            const auto charts=b321i_route_charts(
                external,external_power,shifted);
            const double external_factor=source_(
                marisa_b_halo_v1::norm(
                    external[static_cast<std::size_t>(external_power)]));
            for (const auto& term:reduction.terms) {
                Complex scalar(0.0,0.0);
                if (term.powers[2]==0) {
                    const double integer_scale=std::pow(
                        shifted_scale/reduction_scale,
                        2.0*(term.powers[0]+term.powers[1]));
                    for (const auto& mode_d0:modes_at_shifted_scale) {
                        for (const auto& mode_d1:modes_at_shifted_scale) {
                            const Complex nu0=
                                -static_cast<double>(term.powers[0])
                                -0.5*mode_d0.exponent;
                            const Complex nu1=
                                -static_cast<double>(term.powers[1])
                                -0.5*mode_d1.exponent;
                            scalar+=mode_d0.coefficient
                                    *mode_d1.coefficient
                                    *fftlog_dr_two_propagator_integral(
                                        nu0,nu1);
                            ++result.master_integral_evaluations;
                        }
                    }
                    scalar*=external_factor*integer_scale
                            *shifted_scale*shifted_scale*shifted_scale;
                } else {
                    const auto& centers=charts.at(
                        static_cast<std::size_t>(term.chart));
                    const MasterGeometry geometry=
                        canonical_master_geometry(centers);
                    if (std::fabs(geometry.scale/reduction_scale-1.0)>2.0e-11) {
                        throw std::runtime_error(
                            "B321I chart scale differs from Laurent normalization");
                    }
                    for (const auto& mode_d0:modes_at_reduction_scale) {
                        for (const auto& mode_d1:modes_at_reduction_scale) {
                            std::array<Complex,3> local_nu={{
                                -static_cast<double>(term.powers[0])
                                    -0.5*mode_d0.exponent
                                    +analytic_regulator_epsilon,
                                -static_cast<double>(term.powers[1])
                                    -0.5*mode_d1.exponent
                                    +analytic_regulator_epsilon,
                                -static_cast<double>(term.powers[2])
                                    +analytic_regulator_epsilon}};
                            const auto integral=fftlog_dr_master_integral(
                                local_nu[static_cast<std::size_t>(
                                    geometry.denominator_indices[0])],
                                local_nu[static_cast<std::size_t>(
                                    geometry.denominator_indices[1])],
                                local_nu[static_cast<std::size_t>(
                                    geometry.denominator_indices[2])],
                                geometry.x,geometry.y,master);
                            scalar+=mode_d0.coefficient
                                    *mode_d1.coefficient
                                    *integral.value;
                            ++result.master_integral_evaluations;
                        }
                    }
                    scalar*=external_factor
                            *reduction_scale*reduction_scale*reduction_scale;
                }
                result.value+=scalar.real()*term.coefficient;
                imaginary+=scalar.imag()*term.coefficient;
            }
            result.route_reductions.push_back(std::move(reduction));
        }
    }
    const double real_scale=polynomial_maximum_absolute(result.value);
    const double imaginary_scale=polynomial_maximum_absolute(imaginary);
    result.maximum_imaginary_to_real=
        imaginary_scale/std::max(real_scale,1.0e-300);
    return result;
}

FftlogAnalyticDiagramResult
FftlogDrOracle::evaluate_b321i_public_table_analytic(
    const std::array<Vec3,3>& closed_triangle,
    const FieldKernelProvider& provider,
    FftlogDrMasterConfig master,
    double mode_coefficient_relative_tolerance,
    double analytic_regulator_epsilon,
    std::uint64_t operator_mask) const {
    if (!(mode_coefficient_relative_tolerance>=0.0
          && mode_coefficient_relative_tolerance<1.0)) {
        throw std::invalid_argument(
            "public-table B321I mode tolerance must be in [0,1)");
    }
    if (!(analytic_regulator_epsilon>0.0
          && analytic_regulator_epsilon<1.0e-3)) {
        throw std::invalid_argument(
            "public-table B321I regulator must be in (0,1e-3)");
    }
    const marisa_b_halo_v1::CanonicalTriangle canonical=
        marisa_b_halo_v1::canonicalize_closed_vectors(closed_triangle);
    const std::array<Vec3,3> external={{
        canonical.k1,canonical.k2,canonical.k3}};
    const double short_scale=marisa_b_halo_v1::norm(external[0]);
    const double middle_scale=marisa_b_halo_v1::norm(external[1]);
    const double long_scale=marisa_b_halo_v1::norm(external[2]);
    if (!(short_scale>0.0 && middle_scale>=short_scale
          && long_scale>=middle_scale)) {
        throw std::invalid_argument(
            "public-table B321I requires a non-degenerate canonical triangle");
    }
    const double x=(short_scale/long_scale)*(short_scale/long_scale);
    const double y=(middle_scale/long_scale)*(middle_scale/long_scale);

    const std::vector<FftlogMode> all_modes=power_.modes();
    double maximum_mode_coefficient=0.0;
    for (const auto& mode:all_modes) {
        maximum_mode_coefficient=std::max(
            maximum_mode_coefficient,std::abs(mode.coefficient));
    }
    if (!(maximum_mode_coefficient>0.0
          && std::isfinite(maximum_mode_coefficient))) {
        throw std::runtime_error(
            "public-table B321I has no finite nonzero power-spectrum mode");
    }
    const double threshold=
        mode_coefficient_relative_tolerance*maximum_mode_coefficient;
    std::vector<FftlogMode> modes;
    for (const auto& mode:all_modes) {
        if (std::abs(mode.coefficient)>threshold) modes.push_back(mode);
    }
    if (modes.empty()) {
        throw std::runtime_error(
            "public-table B321I mode pruning removed every mode");
    }

    using CoefficientMatrix=
        std::array<std::array<
            double,generated_public_loops::kB321IFrequencies.size()>,
            kB321IOperatorCount>;
    const std::array<CoefficientMatrix,6> coefficient_matrices={{
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                x,y,generated_public_loops::kB321ICoefficients),
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                y,x,generated_public_loops::kB321ICoefficients),
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                x/y,1.0/y,generated_public_loops::kB321ICoefficients),
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                1.0/y,x/y,generated_public_loops::kB321ICoefficients),
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                1.0/x,y/x,generated_public_loops::kB321ICoefficients),
        generated_public_loop_coefficients<
            kB321IOperatorCount,
            generated_public_loops::kB321IFrequencies.size()>(
                y/x,1.0/x,generated_public_loops::kB321ICoefficients),
    }};
    std::array<bool,
        generated_public_loops::kB321IFrequencies.size()>
        active_frequencies={};
    for (std::size_t operator_index=0;
         operator_index<kB321IOperatorCount;++operator_index) {
        if ((operator_mask&(std::uint64_t{1}<<operator_index))==0) continue;
        for (std::size_t route=0;route<coefficient_matrices.size();++route) {
            for (std::size_t frequency_index=0;
                 frequency_index<
                    generated_public_loops::kB321IFrequencies.size();
                 ++frequency_index) {
                active_frequencies[frequency_index]=
                    active_frequencies[frequency_index]
                    || coefficient_matrices[route][operator_index]
                        [frequency_index]!=0.0;
            }
        }
    }
    if (std::none_of(
            active_frequencies.begin(),active_frequencies.end(),
            [](bool value) { return value; })) {
        throw std::invalid_argument(
            "public-table B321I operator mask selects no active operator");
    }
    const std::array<std::array<int,3>,6> master_permutations={{
        {{0,1,2}},{{1,0,2}},{{0,2,1}},
        {{1,2,0}},{{2,1,0}},{{2,0,1}}}};
    const std::array<int,6> scale_indices={{2,2,1,1,0,0}};
    const std::array<double,3> loop_scales={{
        short_scale,middle_scale,long_scale}};
    const std::array<double,6> shape_ratios={{1.0,1.0,y,y,x,x}};

    struct ScaledMode {
        Complex coefficient;
        Complex exponent;
    };
    std::array<std::vector<ScaledMode>,3> scaled_modes;
    for (std::size_t scale_index=0;scale_index<loop_scales.size();
         ++scale_index) {
        scaled_modes[scale_index].reserve(modes.size());
        for (const auto& mode:modes) {
            const Complex coefficient=mode.coefficient*std::exp(
                mode.exponent*std::log(
                    loop_scales[scale_index]/mode.pivot_k));
            if (!finite(coefficient)) {
                throw std::overflow_error(
                    "public-table B321I scaled mode is non-finite");
            }
            scaled_modes[scale_index].push_back(
                ScaledMode{coefficient,mode.exponent});
        }
    }

    using FrequencyValues=std::array<
        Complex,generated_public_loops::kB321IFrequencies.size()>;
    using MasterCounts=std::array<
        std::size_t,generated_public_loops::kB321IFrequencies.size()>;
    std::array<FrequencyValues,6> frequency_values={};
    std::array<MasterCounts,6> master_counts={};
    std::atomic<bool> failed(false);
    std::exception_ptr parallel_error;
    std::mutex parallel_error_mutex;
    const std::ptrdiff_t work_items=static_cast<std::ptrdiff_t>(
        6*generated_public_loops::kB321IFrequencies.size());
#pragma omp parallel for schedule(dynamic)
    for (std::ptrdiff_t work=0;work<work_items;++work) {
        if (failed.load(std::memory_order_relaxed)) continue;
        try {
            const std::size_t route=static_cast<std::size_t>(work)
                /generated_public_loops::kB321IFrequencies.size();
            const std::size_t frequency_index=
                static_cast<std::size_t>(work)
                %generated_public_loops::kB321IFrequencies.size();
            if (!active_frequencies[frequency_index]) continue;
            const auto& frequency=
                generated_public_loops::kB321IFrequencies[frequency_index];
            const auto& route_modes=scaled_modes[
                static_cast<std::size_t>(scale_indices[route])];
            const auto& permutation=master_permutations[route];
            Complex scalar(0.0,0.0);
            std::size_t count=0;
            for (const auto& first:route_modes) {
                for (const auto& second:route_modes) {
                    const std::array<Complex,2> exponents={{
                        first.exponent,second.exponent}};
                    std::array<Complex,3> unregulated_nu;
                    for (std::size_t denominator=0;
                         denominator<3;++denominator) {
                        const int slot=frequency.fftlog_slot[denominator];
                        unregulated_nu[denominator]=
                            static_cast<double>(
                                frequency.shift[denominator]);
                        if (slot>=0) {
                            if (slot>=2) {
                                throw std::logic_error(
                                    "public B321I frequency has invalid slot");
                            }
                            unregulated_nu[denominator]-=
                                0.5*exponents[
                                    static_cast<std::size_t>(slot)];
                        }
                    }
                    Complex shape_factor(1.0,0.0);
                    if (route>=2) {
                        shape_factor=std::pow(
                            shape_ratios[route],
                            -1.5+unregulated_nu[0]
                                +unregulated_nu[1]
                                +unregulated_nu[2]);
                    }
                    const std::array<Complex,3> master_nu={{
                        unregulated_nu[
                            static_cast<std::size_t>(permutation[0])],
                        unregulated_nu[
                            static_cast<std::size_t>(permutation[1])],
                        unregulated_nu[
                            static_cast<std::size_t>(permutation[2])]}};
                    scalar+=first.coefficient*second.coefficient
                        *shape_factor
                        *master_with_exact_scaleless_reduction(
                            master_nu,analytic_regulator_epsilon,
                            x,y,master);
                    ++count;
                }
            }
            frequency_values[route][frequency_index]=scalar;
            master_counts[route][frequency_index]=count;
        } catch (...) {
            std::lock_guard<std::mutex> lock(parallel_error_mutex);
            if (!parallel_error) parallel_error=std::current_exception();
            failed.store(true,std::memory_order_relaxed);
        }
    }
    if (parallel_error) std::rethrow_exception(parallel_error);

    FftlogAnalyticDiagramResult result;
    result.fftlog_modes_used=static_cast<int>(modes.size());
    result.reduction.basis_terms=
        static_cast<int>(std::count(
            active_frequencies.begin(),active_frequencies.end(),true));
    result.reduction.maximum_validation_absolute_error=0.0;
    result.reduction.maximum_validation_relative_error=0.0;
    const auto operator_polynomials=b321i_operator_polynomials(provider);
    SparsePolynomial imaginary;
    for (std::size_t route=0;route<6;++route) {
        const double loop_scale=loop_scales[
            static_cast<std::size_t>(scale_indices[route])];
        const double route_scale=
            source_(loop_scale)*loop_scale*loop_scale*loop_scale;
        for (std::size_t operator_index=0;
             operator_index<kB321IOperatorCount;++operator_index) {
            if ((operator_mask&(std::uint64_t{1}<<operator_index))==0) {
                continue;
            }
            Complex value(0.0,0.0);
            for (std::size_t frequency_index=0;
                 frequency_index<
                    generated_public_loops::kB321IFrequencies.size();
                 ++frequency_index) {
                value+=coefficient_matrices[route]
                    [operator_index][frequency_index]
                    *frequency_values[route][frequency_index];
            }
            value*=route_scale;
            result.value+=value.real()*operator_polynomials[operator_index];
            imaginary+=value.imag()*operator_polynomials[operator_index];
        }
        for (const std::size_t count:master_counts[route]) {
            result.master_integral_evaluations+=count;
        }
    }
    const double real_scale=polynomial_maximum_absolute(result.value);
    const double imaginary_scale=polynomial_maximum_absolute(imaginary);
    result.maximum_imaginary_to_real=
        imaginary_scale/std::max(real_scale,1.0e-300);
    return result;
}

